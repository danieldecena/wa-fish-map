const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');

const here = p => path.join(__dirname, '..', p);
const RR = require('../river-rules.js');
const Reports = require('../reports.js');
const src = JSON.parse(fs.readFileSync(here('rules/river-rules.json'), 'utf8'));
const realDay = s => /^\d{4}-\d{2}-\d{2}$/.test(s) && new Date(s + 'T00:00:00Z').toISOString().slice(0, 10) === s;

test('every river-rules id is a site in reports.js', () => {
  const ids = new Set(Reports.SITES.map(s => s.id));
  assert.ok(RR.ROWS.length > 0);
  RR.ROWS.forEach(r => assert.ok(ids.has(r.id), 'unknown water: ' + r.id));
  assert.deepEqual([...new Set(RR.ROWS.map(r => r.id))].sort(), ['columbia', 'cowlitz', 'drano', 'kalama', 'klickitat', 'lewis', 'skagit', 'washougal', 'wind']);
});

test('every row has text, a known species, a real checked date and a through date that is not before it', () => {
  RR.ROWS.forEach((r, i) => {
    const at = 'row ' + i + ' (' + r.id + ')';
    assert.ok(['Coho Salmon', 'Chinook Salmon', 'All salmon'].includes(r.species), at + ': species ' + r.species);
    assert.ok(typeof r.text === 'string' && r.text.trim().length > 0, at + ': empty text');
    assert.ok(r.stretch === null || (typeof r.stretch === 'string' && r.stretch.trim()), at + ': bad stretch');
    assert.equal(typeof r.release, 'boolean', at);
    assert.ok(realDay(r.checked), at + ': checked ' + r.checked);
    assert.ok(realDay(r.through), at + ': through ' + r.through);
    assert.ok(r.through >= r.checked, at + ': ends before it was checked');
  });
});

test('rows carry no source label or link, never colour, and never say a fishery is open', () => {
  RR.ROWS.forEach(r => {
    assert.deepEqual(Object.keys(r).sort(), ['checked', 'id', 'release', 'species', 'stretch', 'text', 'through']);
    const t = (r.stretch || '') + ' ' + r.text;
    assert.ok(!/https?:|www\.|\.com|\.gov/.test(t), r.id + ': a link in the text');
    assert.ok(!/\bopen(s|ed|ing)?\b/i.test(t), r.id + ': says open: ' + t);
    assert.ok(!/\b(prime|excellent|good|fair|slow)\b/i.test(r.text), r.id + ': a rating word in the rule text');
  });
});

test('river-rules.js equals the source file, row for row (scripts/build_river_rules.py)', () => {
  const want = [];
  Object.entries(src.waters).forEach(([id, w]) => w.rows.forEach(r => want.push({
    id, species: r.species, stretch: r.stretch === undefined ? null : r.stretch, text: r.text, release: !!r.release, through: r.through, checked: w.checked })));
  assert.deepEqual(RR.ROWS, want, 'river-rules.js is stale: rerun scripts/build_river_rules.py');
  const text = fs.readFileSync(here('river-rules.js'), 'utf8');
  assert.ok(text.startsWith('/* Generated by scripts/build_river_rules.py'), 'generated header');
  assert.ok(/do not edit by hand/.test(text.split('\n')[0]));
});

test('the generator would write exactly this file (--check)', t => {
  const py = '/opt/homebrew/bin/python3';
  if (!fs.existsSync(py)) return t.skip('no ' + py);
  const out = execFileSync(py, [path.join(__dirname, '..', '..', '..', 'scripts', 'build_river_rules.py'), '--check'], { encoding: 'utf8' });
  assert.match(out, /river-rules\.js matches river-rules\.json/);
});

test('forWater drops a row after its through day and keeps it on that day', () => {
  const row = RR.ROWS.find(r => r.id === 'drano' && r.through === '2026-10-31');
  assert.ok(row);
  assert.ok(RR.forWater('drano', '2026-10-31').includes(row));
  assert.ok(!RR.forWater('drano', '2026-11-01').includes(row));
  assert.deepEqual(RR.forWater('drano', '2027-02-01'), []);
  assert.deepEqual(RR.forWater('nowhere', '2026-10-29'), []);
});

test('Chinook release rows carry the release flag, and the known release waters are flagged', () => {
  ['cowlitz', 'columbia', 'skagit'].forEach(id => assert.ok(RR.ROWS.some(r => r.id === id && r.species === 'Chinook Salmon' && r.release), id));
  assert.ok(RR.ROWS.filter(r => r.release).every(r => /release/i.test(r.text)), 'a release flag on a row whose text does not say release');
});

test('index.html loads river-rules.js after rules.js and builds the Rules section from it', () => {
  const html = fs.readFileSync(here('index.html'), 'utf8');
  assert.ok(html.indexOf('<script src="rules.js"></script>') < html.indexOf('<script src="river-rules.js"></script>'));
  assert.match(html, /'<section><h3>Rules for ' \+ esc\(s\.name\)/);
  assert.match(html, /creelHtml\(id\) \+\s*riverRulesHtml\(s\) \+/);
  const fn = html.slice(html.indexOf('function riverRulesHtml'), html.indexOf('function fillSheet'));
  assert.ok(!/<a /.test(fn) && !/\.src\b|\.url\b|label/.test(fn), 'the Rules section builds no link and reads no source');
});

test('river-rules.js is a page file with no network call, and is listed in artifact.json', () => {
  const text = fs.readFileSync(here('river-rules.js'), 'utf8');
  assert.ok(!/\bfetch\s*\(|XMLHttpRequest|sendBeacon|WebSocket|EventSource|\bimport\s*\(/.test(text));
  assert.ok(JSON.parse(fs.readFileSync(here('artifact.json'), 'utf8')).files.includes('river-rules.js'));
});
