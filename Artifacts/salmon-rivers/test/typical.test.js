const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const T = require('../typical.js');
const R = require('../reports.js');

const dir = path.join(__dirname, '..');
const repo = path.join(dir, '..', '..');
const fish = JSON.parse(fs.readFileSync(path.join(repo, 'WAFishMap/Resources/fisheries.json'), 'utf8'));
const src = JSON.parse(fs.readFileSync(path.join(repo, 'site/data/sites.json'), 'utf8'));
const text = fs.readFileSync(path.join(dir, 'typical.js'), 'utf8');

const fw = fish.freshwater;
const byName = rows => Object.fromEntries(rows.map(r => [r.species, r]));
// Months and note exactly as fisheries.json has them; the generator keeps only these keys.
const verbatim = r => {
  const o = { species: r.species, bestMonths: r.bestMonths, goodMonths: r.goodMonths };
  for (const k of ['note', 'years', 'seasonRisk']) if (k in r) o[k] = r[k];
  return o;
};
// FreshwaterGuide.fishery(county:waterbody:), re-derived here from fisheries.json for the cross-check.
const countyRows = c => {
  const o = fw.byCounty[c];
  if (!o || !o.length) return fw.species;
  const names = new Set(o.map(r => r.species));
  return o.concat(fw.species.filter(r => !names.has(r.species)));
};
const waterRows = (c, wb) => {
  const base = countyRows(c);
  const rows = wb && fw.byWaterbody[wb];
  if (!rows || !rows.length) return base;
  const names = new Set(rows.map(r => r.species));
  return rows.concat(base.filter(r => !names.has(r.species)));
};

test('the generated file says so, with a date', () => {
  const head = text.split('\n').slice(0, 3).join('\n');
  assert.match(head, /Generated by scripts\/build_typical_sites\.py on \d{4}-\d{2}-\d{2}; Generated, do not edit\./);
  assert.match(T.generated, /^\d{4}-\d{2}-\d{2}$/);
  assert.ok(!Number.isNaN(Date.parse(T.generated)));
  assert.ok(head.includes(T.generated), 'header date is the data date');
});

test('site ids are unique and every site has the fields the page reads', () => {
  const ids = T.sites.map(s => s.id);
  assert.equal(new Set(ids).size, ids.length, 'duplicate site id');
  assert.ok(T.sites.length >= 500);
  for (const s of T.sites) {
    assert.ok(['pier', 'launch', 'access'].includes(s.kind), `${s.id} kind ${s.kind}`);
    assert.ok(s.name && typeof s.name === 'string', s.id);
    assert.ok(s.lat > 45.4 && s.lat < 49.1 && s.lon > -124.9 && s.lon < -116.9, `${s.id} outside Washington`);
    assert.equal(Math.round(s.lat * 1e4) / 1e4, s.lat, `${s.id} lat not rounded to 4 decimals`);
    assert.equal(Math.round(s.lon * 1e4) / 1e4, s.lon, `${s.id} lon not rounded to 4 decimals`);
    assert.ok(s.guide === null || (Number.isInteger(s.guide) && s.guide >= 0 && s.guide < T.guides.length), `${s.id} guide index`);
  }
});

test('the sites are the WDFW sites in site/data/sites.json, none dropped', () => {
  assert.equal(T.sites.length, src.sites.length);
  assert.deepEqual(T.sites.map(s => s.id), src.sites.map(s => s.id));
  assert.equal(T.sites.filter(s => s.kind === 'pier').length, src.counts.pier);
  assert.equal(T.sites.filter(s => s.kind !== 'pier').length, src.counts.access);
  const launches = new Set(src.sites.filter(s => s.kind === 'access' && s.launch).map(s => s.id));
  for (const s of T.sites) if (s.kind !== 'pier') assert.equal(s.kind === 'launch', launches.has(s.id), s.id);
});

test('every month in every guide is 1-12', () => {
  for (const g of T.guides) for (const r of g.rows) {
    for (const m of r.bestMonths.concat(r.goodMonths)) assert.ok(Number.isInteger(m) && m >= 1 && m <= 12, `${g.scope} ${r.species} month ${m}`);
  }
  for (const t of T.seasonRisk) for (const m of t.months) assert.ok(m >= 1 && m <= 12);
});

test('every species name is an exact name in fisheries.json', () => {
  const all = new Set();
  fish.areas.forEach(a => a.species.forEach(s => all.add(s.species)));
  fw.species.forEach(s => all.add(s.species));
  Object.values(fw.byCounty).forEach(l => l.forEach(s => all.add(s.species)));
  Object.values(fw.byWaterbody).forEach(l => l.forEach(s => all.add(s.species)));
  assert.ok(all.size >= 25, 'control: the extractor read the vocabulary');
  for (const g of T.guides) for (const r of g.rows) assert.ok(all.has(r.species), `"${r.species}" is not in fisheries.json`);
  for (const s of T.species) assert.ok(all.has(s.name), `chip "${s.name}" is not in fisheries.json`);
  const used = new Set(T.guides.flatMap(g => g.rows.map(r => r.species)));
  assert.deepEqual(T.species.map(s => s.name), [...used].sort(), 'chips are exactly the species some site has guidance for');
  assert.ok(T.species.length >= 22);
});

test('every site area id exists, and a site is marine exactly when its guide is that area', () => {
  const fishAreas = new Set(fish.areas.map(a => a.areaName));
  for (const id of Object.keys(T.areas)) assert.ok(fishAreas.has(id), `area ${id} has no guidance in fisheries.json`);
  assert.ok(!('Oregon' in T.areas));
  for (const s of T.sites) {
    if (s.area === null) { assert.notEqual(s.guide === null ? 'x' : T.guides[s.guide].kind, 'marine', `${s.id} has no area but a marine guide`); continue; }
    assert.ok(s.area in T.areas, `${s.id}: area ${s.area} missing`);
    assert.equal(T.guides[s.guide].kind, 'marine', s.id);
    assert.equal(T.guides[s.guide].area, s.area, s.id);
  }
});

test('marine guides copy the fisheries.json area rows verbatim', () => {
  const marine = T.guides.filter(g => g.kind === 'marine');
  assert.ok(marine.length >= 10);
  assert.equal(new Set(marine.map(g => g.area)).size, marine.length, 'one guide per area');
  for (const g of marine) {
    assert.ok(g.area in T.areas, `guide for unlisted area ${g.area}`);
    const a = fish.areas.find(x => x.areaName === g.area);
    assert.deepEqual(g.rows, a.species.map(verbatim), `area ${g.area}`);
  }
});

test('freshwater guides reproduce the app tiers: statewide, county, waterbody', () => {
  const fresh = T.guides.filter(g => g.kind === 'fresh');
  assert.ok(fresh.length > 10);
  let checked = 0;
  for (const s of T.sites) {
    if (s.guide === null || T.guides[s.guide].kind !== 'fresh') continue;
    const g = T.guides[s.guide];
    const [tier, key] = g.scope.split(/:(.*)/s);
    if (tier === 'statewide') assert.ok(!fw.byCounty[s.county], `${s.id}: ${s.county} has county rows but the site was scoped statewide`);
    else if (tier === 'county') assert.equal(key, s.county, s.id);
    else assert.equal(tier, 'waterbody', `unknown scope ${g.scope}`);
    const full = waterRows(s.county, tier === 'waterbody' ? key : null);
    // A lake can narrow the list, never reorder it or change a row.
    const want = full.map(verbatim);
    let at = 0;
    for (const r of g.rows) {
      const i = want.findIndex((w, j) => j >= at && JSON.stringify(w) === JSON.stringify(r));
      assert.ok(i >= 0, `${s.id} (${g.scope}): row ${r.species} is not a verbatim, in-order row of the app's list`);
      at = i + 1;
    }
    checked++;
  }
  assert.ok(checked > 400, `only ${checked} freshwater sites checked`);
  // The unfiltered statewide list is present as the app shows it.
  assert.ok(fresh.some(g => g.scope === 'statewide' && g.rows.length === fw.species.length));
});

test('known-good matches: shore-snapped launches get their marine area, curated lake ramps stay freshwater', () => {
  const site = n => { const s = T.sites.find(x => x.name === n); assert.ok(s, `no site ${n}`); return s; };
  // CLAUDE.md: Boston Harbor (30 m) and Point No Point (65 m) sit outside their polygons and snap in.
  assert.equal(site('Boston Harbor').area, '13');
  assert.equal(site('Point No Point').area, '9');
  // A curated Potholes ramp keeps its waterbody rows and is never snapped into a marine area.
  const blythe = site('Blythe');
  assert.equal(blythe.area, null);
  assert.equal(T.guides[blythe.guide].scope, 'waterbody:Potholes Reservoir');
  assert.ok(T.guides[blythe.guide].rows.some(r => r.species === 'Walleye'));
  // Every pier is on salt water in this data (the app matches all 63).
  assert.ok(T.sites.filter(s => s.kind === 'pier').every(s => s.area !== null));
  // The detector can fail: an inland ramp must come back with no area.
  assert.equal(site('Cow Lake').area, null);
});

