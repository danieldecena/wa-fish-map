const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { spawnSync } = require('node:child_process');
const R = require('../reports.js');
const T = require('../typical.js');
const C = require('../creel.js');

const dir = path.join(__dirname, '..');
const repo = path.join(dir, '..', '..');
const read = f => fs.readFileSync(path.join(dir, f), 'utf8');
const text = read('creel.js');
const SITES = Object.entries(C.SITES);
const isCount = n => n === null || (Number.isInteger(n) && n >= 0);
// The columns of https://wdfw.wa.gov/fishing/reports/creel/puget that are counts of fish, in the page's order.
// "Chinook (per angler)" is a rate and is deliberately not kept.
const SOURCE_SPECIES = ['Chinook', 'Coho', 'Chum', 'Pink', 'Sockeye', 'Lingcod', 'Halibut'];
const ROW_KEYS = ['anglers', 'catchArea', 'interviews', 'match', 'ramp', 'source', 'species', 'surveyDays', 'windowEnd', 'windowStart'];
const normalize = s => s.toLowerCase().replace(/&/g, ' and ').replace(/[^a-z0-9]+/g, ' ').replace(/\s+/g, ' ').trim();
// Whole days from a to b (b - a); throws on a malformed or impossible date.
const between = (a, b) => R.ageDays(a, b);

test('creel.js is generated: header with a date, no em dash, under 300 KB', () => {
  const first = text.split('\n')[0];
  assert.match(first, /^\/\* Generated by scripts\/build_creel_sites\.py on \d{4}-\d{2}-\d{2}; do not edit by hand\. \*\/$/);
  assert.equal(first.match(/on (\d{4}-\d{2}-\d{2})/)[1], C.GENERATED);
  between(C.GENERATED, C.GENERATED);
  assert.doesNotMatch(text, /—/);
  assert.ok(Buffer.byteLength(text) < 300 * 1024, `${Buffer.byteLength(text)} bytes`);
});

test('control: creel.js has sites to check, and forSite only answers for real ids', () => {
  assert.ok(SITES.length >= 1, 'no sites: every loop below would pass on nothing');
  assert.equal(C.forSite('nowhere'), null);
  assert.equal(C.forSite('toString'), null, 'an inherited property is not a site');
  assert.equal(C.forSite('constructor'), null);
  assert.deepEqual(C.SPECIES, SOURCE_SPECIES);
});

test('every site id is a site in typical.js', () => {
  const ids = new Set(T.sites.map(s => s.id));
  for (const [id] of SITES) assert.ok(ids.has(id), `${id} is not in typical.js`);
});

test('every row has exactly the agreed fields, and counts are non-negative integers or null', () => {
  for (const [id, c] of SITES) {
    assert.ok(c.rows.length > 0, `${id} has no rows; it should have been left out`);
    for (const r of c.rows) {
      assert.deepEqual(Object.keys(r).sort(), ROW_KEYS, id);
      for (const k of ['anglers', 'interviews']) assert.ok(isCount(r[k]), `${id}/${k} = ${r[k]}`);
      assert.ok(Number.isInteger(r.surveyDays) && r.surveyDays >= 1, `${id} surveyDays`);
      assert.ok(Object.keys(r.species).length > 0, `${id} has no species columns`);
      for (const [k, v] of Object.entries(r.species)) assert.ok(isCount(v), `${id}/${k} = ${v}`);
    }
  }
});

test('no species key outside the source columns, and no rate or steelhead', () => {
  for (const [id, c] of SITES) {
    for (const r of c.rows) {
      for (const k of Object.keys(r.species)) assert.ok(SOURCE_SPECIES.includes(k), `${id}: "${k}" is not a column on the WDFW page`);
    }
  }
  assert.doesNotMatch(text, /per angler|steelhead/i);
});

test('windows are real ISO dates, start is not after end, and they sit inside the filter and the build date', () => {
  for (const [id, c] of SITES) {
    const n = +/^Last (\d+) days$/.exec(c.filter)[1];
    assert.ok([15, 30, 60].includes(n), `${id} filter "${c.filter}"`);
    for (const r of c.rows) {
      // between() throws on a malformed or impossible date (2026-02-31).
      assert.ok(between(r.windowStart, r.windowEnd) >= 0, `${id}: start ${r.windowStart} is after end ${r.windowEnd}`);
      assert.ok(between(r.windowEnd, C.GENERATED) >= 0, `${id}: window ends after the build date`);
      assert.ok(between(r.windowStart, C.GENERATED) < n, `${id}: window starts more than ${n} days before the build date`);
      assert.ok(r.surveyDays <= between(r.windowStart, r.windowEnd) + 1, `${id}: more survey days than days in the window`);
    }
    assert.equal(c.windowStart, r0(c, 'windowStart', Math.min), `${id} site window start`);
    assert.equal(c.windowEnd, r0(c, 'windowEnd', Math.max), `${id} site window end`);
  }
});
function r0(c, k, pick) {
  const ms = c.rows.map(r => Date.parse(r[k]));
  return new Date(pick(...ms)).toISOString().slice(0, 10);
}

test('every row cites its WDFW source page', () => {
  for (const [id, c] of SITES) {
    for (const r of c.rows) assert.match(r.source, /^https:\/\/wdfw\.wa\.gov\/fishing\/reports\/creel\/puget\?/, id);
  }
});

test('matching held: each row came from a source ramp whose name equals the map site name exactly', () => {
  const name = Object.fromEntries(T.sites.map(s => [s.id, normalize(s.name)]));
  for (const [id, c] of SITES) {
    for (const r of c.rows) {
      assert.ok(['exact-name', 'name+coordinates'].includes(r.match), `${id}: match rule "${r.match}"`);
      if (r.match === 'exact-name') {
        for (const part of r.ramp.split(' + ')) assert.equal(normalize(part), name[id], `${id}: source ramp "${part}" is not the site's name`);
      }
    }
  }
});

