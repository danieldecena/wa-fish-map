test('the sheet section: heading, the not-ratings line verbatim once, a failure-tolerant load, Typical season only', () => {
  const html = read('index.html');
  const line = 'Counts from WDFW angler surveys, raw data that can change after review. They are not ratings, and a site with no row was not sampled.';
  assert.equal(html.split(line).length - 1, 1, 'the sentence is defined once, verbatim');
  assert.match(html, /<h3>Recent WDFW creel counts<\/h3>/);
  assert.match(html, /typeof CreelSites !== 'undefined' \? CreelSites\.forSite\(id\) : null/);
  assert.match(html, /<script src="creel\.js"><\/script>/);
  assert.match(html, /CREEL_OLD_DAYS = 14;/);
  const typical = html.slice(html.indexOf('function fillTypical'), html.indexOf('function fillSheet'));
  assert.match(typical, /creelSiteHtml\(id\)/, 'Typical sheets show it');
  const reports = html.slice(html.indexOf('function fillSheet'), html.indexOf('var returnFocus'));
  assert.doesNotMatch(reports, /creelSiteHtml|CreelSites/, 'Recent reports sheets do not');
  assert.doesNotMatch(html, /—/);
});

// ---- matching rules, pinned with a small fixture through the generator itself ----

function runFixture() {
  const script = path.join(repo, 'scripts', 'build_creel_sites.py');
  const fixture = path.join(__dirname, 'creel-fixture.json');
  for (const py of ['/opt/homebrew/bin/python3', 'python3']) {
    const r = spawnSync(py, [script, '--fixture', fixture], { encoding: 'utf8' });
    if (r.error) continue;
    assert.equal(r.status, 0, r.stderr);
    return JSON.parse(r.stdout);
  }
  return null;
}
const FX = runFixture();
const skipFx = FX ? false : 'python3 not available';

test('fixture: an exact normalized-name match is made (case and punctuation ignored)', { skip: skipFx }, () => {
  assert.deepEqual(FX.matched['ALPHA  ramp'], ['alpha-ramp', 'exact-name']);
  assert.deepEqual(FX.matched['alpha-ramp'], ['alpha-ramp', 'exact-name']);
});

test('fixture: near misses are NOT matched (a ramp is not the pier of the same name, a shared name is ambiguous, a far coordinate fails)', { skip: skipFx }, () => {
  assert.ok(!('Kingston Public Ramp' in FX.matched), 'Kingston Public Ramp must not match Kingston Public Pier');
  assert.match(FX.unmatched['Kingston Public Ramp'], /no site has this normalized name/);
  assert.ok(!('Silver Lake' in FX.matched));
  assert.match(FX.unmatched['Silver Lake'], /^ambiguous: 2 sites/);
  assert.ok(!('Beta Dock' in FX.matched));
  assert.match(FX.unmatched['Beta Dock'], /within 1 km/);
  for (const sid of Object.keys(FX.sites)) assert.ok(!['kingston-pier', 'silver-lake-a', 'silver-lake-b', 'beta-dock'].includes(sid), `${sid} must have no counts`);
  assert.deepEqual(FX.matched['Gamma Dock'], ['gamma-dock', 'name+coordinates']);
});

test('fixture: several ramps for one site are summed only when sampled on the same days', { skip: skipFx }, () => {
  const a = FX.sites['alpha-ramp'].rows;
  assert.equal(a.length, 1, 'same two days: one summed row');
  assert.equal(a[0].interviews, 2 + 1 + 4 + 3);
  assert.equal(a[0].anglers, 5 + 2 + 9 + 7);
  assert.deepEqual(a[0].species, { Chinook: 0 + 0 + 1 + 0, Coho: 3 + 1 + 6 + 2 });
  assert.equal(a[0].surveyDays, 2);
  assert.ok(FX.notes.some(n => /alpha-ramp .*summed$/.test(n)));
  const d = FX.sites['delta-ramp'].rows;
  assert.equal(d.length, 2, 'different days: kept apart, not added together');
  assert.deepEqual(d.map(r => r.surveyDays).sort(), [1, 2]);
  assert.ok(FX.notes.some(n => /delta-ramp .*kept separate/.test(n)));
});

test('fixture: a blank stays null, a zero stays zero, and one blank day makes the window total null', { skip: skipFx }, () => {
  const r = FX.sites['nulls-ramp'].rows[0];
  assert.equal(r.anglers, null, 'anglers was blank on one day');
  assert.equal(r.interviews, 5);
  assert.equal(r.species.Coho, 0);
  assert.equal(r.species.Chinook, null);
});
