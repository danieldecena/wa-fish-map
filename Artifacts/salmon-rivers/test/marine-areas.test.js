const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const dir = path.join(__dirname, '..');
const read = f => fs.readFileSync(path.join(dir, f), 'utf8');
const src = read('marine-areas.js');
const M = require('../marine-areas.js');
const T = require('../typical.js');
global.window = global;
require('../geo.js');
const G = global.GEO;
const OCEAN = ['1', '2', '3', '4'];   // the four coastal ocean areas run out to -129 degrees; bbox is cut to the pan window
const NO_SITES = ['1', '2', '3', '4']; // areas that hold no pier, launch or shore site in typical.js

const nums = d => (d.match(/-?\d+(?:\.\d+)?/g) || []).map(Number);

test('marine-areas.js: generated header, UMD wrapper, window.MARINE_AREAS', () => {
  assert.match(src, /^\/\* Generated by scripts\/build_marine_areas\.py; do not edit by hand\./);
  assert.match(src, /else root\.MARINE_AREAS = factory\(\);/);
  assert.equal(typeof M, 'object');
});

test('marine-areas.js: keyed by exactly the ids of typical.js areas (so by site.area), no Oregon', () => {
  assert.deepEqual(Object.keys(M).sort(), Object.keys(T.areas).sort());
  assert.equal(Object.keys(M).length, 16);
  assert.ok(!('Oregon' in M));
  Object.keys(M).forEach(id => assert.equal(M[id].title, T.areas[id].title, `title of ${id} equals typical.js`));
  // Every site's area is an area with an outline: a site cannot point at a missing key.
  T.sites.forEach(s => { if (s.area) assert.ok(M[s.area], `${s.id}: area ${s.area} has an outline`); });
});

test('marine-areas.js: each area is { title, d, bbox, centroid } and nothing else', () => {
  Object.entries(M).forEach(([id, a]) => {
    assert.deepEqual(Object.keys(a).sort(), ['bbox', 'centroid', 'd', 'title'], id);
    assert.match(a.d, /^(M-?[\d.]+( -?[\d.]+)+Z)+$/, `${id}: one path of closed rings`);
    const n = nums(a.d);
    assert.equal(n.length % 2, 0, `${id}: whole x y pairs`);
    assert.ok(n.every(Number.isFinite));
    assert.equal(a.bbox.length, 2); assert.equal(a.centroid.length, 2);
  });
});

test('marine-areas.js: the file stays under 90 KB', () => {
  assert.ok(Buffer.byteLength(src) < 90000, `${Buffer.byteLength(src)} bytes`);
});

test('marine-areas.js: bbox sits inside the state box (ocean areas: inside the pan window), and holds the centroid', () => {
  const [[sx0, sy0], [sx1, sy1]] = G.bounds.state, slack = 0.01;
  const m = Math.max(sx1 - sx0, sy1 - sy0) * 0.025;   // clampView's margin past the border: the camera cannot go further
  Object.entries(M).forEach(([id, a]) => {
    const [[x0, y0], [x1, y1]] = a.bbox;
    assert.ok(x0 < x1 && y0 < y1, `${id}: a real box`);
    const lim = OCEAN.includes(id) ? m : 0;
    assert.ok(x0 >= sx0 - lim - slack && y0 >= sy0 - lim - slack && x1 <= sx1 + lim + slack && y1 <= sy1 + lim + slack, `${id}: bbox ${JSON.stringify(a.bbox)} inside the state box (+${lim.toFixed(1)})`);
    assert.ok(a.centroid[0] >= x0 && a.centroid[0] <= x1 && a.centroid[1] >= y0 && a.centroid[1] <= y1, `${id}: centroid inside bbox`);
  });
});

test('marine-areas.js: the sites of an area lie inside its bbox or touch it, and every area has a site or is listed as empty', () => {
  const x = (lon) => (lon - G.proj.lon0) * G.proj.kx, y = (lat) => (G.proj.lat0 - lat) * G.proj.k;
  const per = {};
  T.sites.forEach(s => { if (s.area) (per[s.area] = per[s.area] || []).push(s); });
  Object.keys(M).forEach(id => {
    if (NO_SITES.includes(id)) { assert.ok(!per[id], `${id} is listed as empty but has sites`); return; }
    assert.ok(per[id] && per[id].length > 0, `${id} has no site and is not listed as empty`);
    const [[x0, y0], [x1, y1]] = M[id].bbox, pad = 3;   // a pier is recorded at the shore end, a little outside the water polygon
    per[id].forEach(s => assert.ok(x(s.lon) >= x0 - pad && x(s.lon) <= x1 + pad && y(s.lat) >= y0 - pad && y(s.lat) <= y1 + pad, `${s.id} sits near area ${id}`));
  });
  assert.equal(per['11'].length, 8, 'Marine Area 11 holds eight sites');
});

test('marine-areas.js: no source label, link or request in the file', () => {
  assert.doesNotMatch(src, /https?:|wdfw\.wa\.gov|220-311/i, 'credit lives in the README, not in what the page ships');
  assert.doesNotMatch(src, /\bfetch\s*\(|XMLHttpRequest|sendBeacon|WebSocket|EventSource|\bimport\s*\(/);
});

test('marine-areas.js is shipped: loaded after typical.js, in artifact.json files, and in the README table', () => {
  const html = read('index.html');
  const i = html.indexOf('<script src="typical.js"></script>'), j = html.indexOf('<script src="marine-areas.js"></script>');
  assert.ok(i > 0 && j > i, 'index.html loads marine-areas.js after typical.js');
  assert.ok(JSON.parse(read('artifact.json')).files.includes('marine-areas.js'));
  assert.match(read('README.md'), /\| `marine-areas\.js` \|/);
  assert.match(read('README.md'), /WAC 220-311-010/, 'the README carries the credit');
});
