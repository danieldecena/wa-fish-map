// ---- the Columbia sum, checked against the table ----
const DB = path.join(os.homedir(), 'database', 'salmon-rivers', 'salmon.db');
const sql = q => {
  const r = spawnSync('sqlite3', ['-readonly', '-json', DB, q], { encoding: 'utf8' });
  if (r.status !== 0) throw new Error('sqlite3 failed: ' + r.stderr);
  return r.stdout.trim() ? JSON.parse(r.stdout) : [];
};
const HAVE_DB = spawnSync('sqlite3', ['--version']).status === 0 && fs.existsSync(DB);
const weekText = w => w.weekStart + ' to ' + w.weekEnd.slice(5);

test('Lower Columbia sums equal the section rows in the salmon table (read live from the db)',
  { skip: HAVE_DB ? false : 'sqlite3 or ~/database/salmon-rivers/salmon.db not available; the pinned fixture test runs instead' },
  () => {
    const w = C.WATERS.columbia;
    const week = weekText(w);
    const where = `River LIKE 'Lower Columbia, Sec %' AND Week = '${week}'`;
    const sections = sql(`SELECT count(DISTINCT River) AS n FROM board WHERE ${where}`)[0].n;
    assert.ok(sections >= 2, `the table has ${sections} Columbia sections for ${week}; the check would prove nothing`);
    // Anglers is a section total repeated on each species row, so it is summed once per section.
    const anglers = sql(`SELECT sum(a) AS s FROM (SELECT DISTINCT River, Anglers AS a FROM board WHERE ${where})`)[0].s;
    for (const r of w.rows) {
      const q = sql(`SELECT sum(Kept) AS k, sum(Released) AS r, count(*) AS n FROM board WHERE ${where} AND Species = '${r.species}'`)[0];
      assert.ok(q.n >= 1, `${r.species}: no table rows for ${week}`);
      assert.equal(r.kept, q.k, `${r.species} kept`);
      assert.equal(r.released, q.r, `${r.species} released`);
      assert.equal(r.anglers, anglers, `${r.species} anglers`);
    }
    // Every salmon species the table has for these sections is in counts.js.
    const inTable = sql(`SELECT DISTINCT Species AS s FROM board WHERE ${where}`).map(x => x.s).filter(s => SALMON.includes(s)).sort();
    assert.deepEqual(w.rows.map(r => r.species).sort(), inTable);
  });

test('every water shows the newest week the table has for it (read live from the db)',
  { skip: HAVE_DB ? false : 'sqlite3 or ~/database/salmon-rivers/salmon.db not available' },
  () => {
    const rivers = {
      cowlitz: "River IN ('Cowlitz, above I-5 Br', 'Cowlitz, below I-5 Br')",
      columbia: "River LIKE 'Lower Columbia, Sec %'",
      lewis: "River = 'Lewis'",
      wind: "River = 'Wind'",
      drano: "River = 'Drano Lake'",
      klickitat: "River IN ('Klickitat, below Fisher Hill Br', 'Klickitat, above Fisher Hill Br')",
      kalama: "River = 'Kalama'",
      washougal: "River = 'Washougal'",
    };
    for (const [id, w] of WATERS) {
      // A water showing a no-catch week also counts that table entry as its newest.
      const names = SALMON.concat(w.noCatch ? ['(no catch)'] : []).map(s => `'${s}'`).join(',');
      const newest = sql(`SELECT max(Week) AS w FROM board WHERE ${rivers[id]} AND Species IN (${names})`)[0].w;
      assert.equal(weekText(w), newest, `${id} is not showing its newest week`);
    }
  });

test('Kalama and Washougal match the table: Kalama\'s coho row, Washougal\'s lone no-catch entry (read live from the db)',
  { skip: HAVE_DB ? false : 'sqlite3 or ~/database/salmon-rivers/salmon.db not available' },
  () => {
    const k = C.WATERS.kalama, w = C.WATERS.washougal;
    const kq = sql(`SELECT Anglers, Kept, Released FROM board WHERE River = 'Kalama' AND Species = 'Coho Salmon' AND Week = '${weekText(k)}'`);
    assert.equal(kq.length, 1);
    assert.deepEqual([k.rows[0].anglers, k.rows[0].kept, k.rows[0].released], [kq[0].Anglers, kq[0].Kept ?? null, kq[0].Released ?? null]);
    const wq = sql(`SELECT Species, Anglers FROM board WHERE River = 'Washougal' AND Week = '${weekText(w)}'`);
    assert.deepEqual(wq.map(x => x.Species), ['(no catch)']);
    assert.equal(w.noCatch.anglers, wq[0].Anglers);
  });

// Pinned copy of the Coho Salmon rows of the Lower Columbia sections for the week of 2026-10-05,
// taken from the table. Used only where sqlite3 or the db is missing (CI, another machine).
const FIXTURE = {
  weekStart: '2026-10-05',
  species: 'Coho Salmon',
  // Sec 9 reported 8 anglers but no coho row, so it counts for anglers only.
  sections: [
    { sec: 1, anglers: 24, kept: 3, released: null },
    { sec: 2, anglers: 58, kept: 10, released: 1 },
    { sec: 4, anglers: 51, kept: 12, released: null },
    { sec: 5, anglers: 54, kept: 36, released: null },
    { sec: 6, anglers: 72, kept: 19, released: 1 },
    { sec: 7, anglers: 29, kept: 20, released: null },
    { sec: 8, anglers: 57, kept: 24, released: 1 },
    { sec: 9, anglers: 8, kept: null, released: null },
  ],
};
const sum = xs => (xs.every(x => x === null) ? null : xs.reduce((a, b) => a + (b || 0), 0));

test('Lower Columbia sums equal the pinned section rows (fixture, for machines without the db)', t => {
  const w = C.WATERS.columbia;
  if (w.weekStart !== FIXTURE.weekStart) {
    if (HAVE_DB) return t.skip(`counts.js moved on to ${w.weekStart}; the live db test covers it`);
    assert.fail(`counts.js is for ${w.weekStart} but the pinned fixture is for ${FIXTURE.weekStart}; refresh FIXTURE from the table`);
  }
  const row = w.rows.find(r => r.species === FIXTURE.species);
  assert.ok(row, 'fixture species missing from counts.js');
  assert.equal(row.anglers, sum(FIXTURE.sections.map(s => s.anglers)));
  assert.equal(row.kept, sum(FIXTURE.sections.map(s => s.kept)));
  assert.equal(row.released, sum(FIXTURE.sections.map(s => s.released)));
  assert.equal(w.note, 'Sections that reported: ' + FIXTURE.sections.map(s => s.sec).join(', ') + '.');
});

test('a blank stays blank: the sum helper does not turn all-null into 0', () => {
  assert.equal(sum([null, null]), null);
  assert.equal(sum([null, 2]), 2);
  assert.equal(sum([0, 0]), 0);
});

