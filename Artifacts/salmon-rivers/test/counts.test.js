const dir = path.join(__dirname, '..');
const read = f => fs.readFileSync(path.join(dir, f), 'utf8');
const WATERS = Object.entries(C.WATERS);
const SALMON = ['Coho Salmon', 'Coho Salmon (jack)', 'Chinook Salmon', 'Chinook Salmon (jack)'];
const isCount = n => n === null || (Number.isInteger(n) && n >= 0);
const TODAY = '2026-10-18';

