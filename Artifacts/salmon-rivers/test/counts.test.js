test('every water id is a river on the page', () => {
  const ids = R.SITES.map(s => s.id);
  for (const [id] of WATERS) assert.ok(ids.includes(id), `${id} is not in Reports.SITES`);
});

test('every water has a real ISO week, a six-day span, a matching label and a WDFW PDF source', () => {
  for (const [id, w] of WATERS) {
    // ageDays throws on a malformed or impossible date (2026-02-31).
    const start = R.ageDays(w.weekStart, w.weekStart) === 0 && w.weekStart;
    const end = R.ageDays(w.weekEnd, w.weekEnd) === 0 && w.weekEnd;
    assert.ok(start && end, `${id} dates`);
    assert.equal(R.ageDays(w.weekStart, w.weekEnd), 6, `${id} should span seven days, start to end`);
    assert.equal(w.week, R.formatDay(w.weekStart) + ' to ' + R.formatDay(w.weekEnd), `${id} label`);
    assert.match(w.source, /^https:\/\/wdfw\.wa\.gov\/.+-(\d{4})\.pdf$/, `${id} source`);
    assert.ok(w.source.endsWith('-' + w.weekEnd.slice(0, 4) + '.pdf'), `${id}: PDF year differs from the week end year`);
    assert.ok(R.ageDays(w.weekEnd, TODAY) >= 0, `${id}: week ends in the future`);
  }
});

test('every row has exactly the agreed fields and only non-negative integers or null', () => {
  for (const [id, w] of WATERS) {
    assert.ok(w.rows.length > 0 || w.noCatch, `${id} has no rows; it should have been left out`);
    if (w.noCatch) {
      // A week whose only entry is "no catch": an angler count and no species rows, never a made-up zero.
      assert.deepEqual(Object.keys(w.noCatch), ['anglers'], id);
      assert.ok(Number.isInteger(w.noCatch.anglers) && w.noCatch.anglers > 0, `${id} noCatch anglers`);
      assert.equal(w.rows.length, 0, `${id}: noCatch and species rows together`);
    }
    for (const r of w.rows) {
      assert.deepEqual(Object.keys(r).sort(), ['anglers', 'kept', 'released', 'section', 'species'], id);
      assert.ok(r.section === null || (typeof r.section === 'string' && r.section.length > 0), `${id} section`);
      for (const k of ['anglers', 'kept', 'released']) assert.ok(isCount(r[k]), `${id}/${r.species}/${k} = ${r[k]}`);
    }
  }
});

