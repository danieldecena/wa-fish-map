// Artifacts/salmon-rivers/test/tide-engine.test.js
'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const Tides = require('../tides.js');
const TP = require('../tide-predictor.js');

const ctx = { window: {} };
vm.createContext(ctx);
['tide-harmonics.js', 'tides-data.js'].forEach(f => vm.runInContext(fs.readFileSync(path.join(__dirname, '..', f), 'utf8'), ctx));
const H = ctx.window.TIDE_HARMONICS, NOAA = ctx.window.TIDES;
const E = Tides.engine(H, TP);
const toMin = s => Date.UTC(+s.slice(0, 4), +s.slice(5, 7) - 1, +s.slice(8, 10), +s.slice(11, 13), +s.slice(14, 16)) / 60000;
const q = (a, p) => { a = a.slice().sort((x, y) => x - y); return a[Math.floor(p * (a.length - 1))]; };

test('every bundled station has a computable tide model, subordinates through a harmonic reference', () => {
  assert.equal(E.stations.length, NOAA.stations.length);
  NOAA.stations.forEach(s => assert.ok(E.day(s.id, NOAA.start), s.name));
});

// The oracle is NOAA's own published high/low predictions (tides-data.js, scripts/build_tides.py). Measured 2026-10-26 over 1,398 tides:
// time median 2 min, 95th percentile 5 min, worst 29 min (a near-flat slack); height median 0.08 ft, 95th percentile 0.22 ft, worst 0.30 ft.
test('computed highs and lows match NOAA predictions across every station for two weeks', () => {
  const days = [];
  for (let t = Date.parse(NOAA.start + 'T00:00:00Z'); days.length < 14; t += 86400000) days.push(new Date(t).toISOString().slice(0, 10));
  const dt = [], dh = [];
  let unmatched = 0;
  for (const st of NOAA.stations) {
    const ours = days.flatMap(d => E.day(st.id, d).map(x => ({ min: toMin(d + ' ' + x.t), type: x.type, v: x.v })));
    for (const r of NOAA.predictions[st.id].filter(r => days.includes(r[0].slice(0, 10)))) {
      let best = null;
      for (const x of ours) if (x.type === r[1]) { const d = Math.abs(x.min - toMin(r[0])); if (!best || d < best.d) best = { d, x }; }
      if (!best || best.d > 120) { unmatched++; continue; }
      dt.push(best.d); dh.push(Math.abs(best.x.v - r[2]));
    }
  }
  assert.ok(dt.length > 1000, 'control: enough tides compared');
  assert.ok(unmatched <= 2, `${unmatched} NOAA tides had no computed tide within 2 hours`);
  assert.ok(q(dt, 0.5) <= 3 && q(dt, 0.95) <= 8 && q(dt, 1) <= 35, `time error median ${q(dt, 0.5)}, p95 ${q(dt, 0.95)}, max ${q(dt, 1)} min`);
  assert.ok(q(dh, 0.5) <= 0.12 && q(dh, 0.95) <= 0.3 && q(dh, 1) <= 0.45, `height error median ${q(dh, 0.5)}, p95 ${q(dh, 0.95)}, max ${q(dh, 1)} ft`);
});

test('a day is Washington-local: midnight in PDT and PST, and every tide listed falls on that date', () => {
  assert.equal(Tides.laMidnight('2026-10-26').toISOString(), '2026-10-26T07:00:00.000Z');
  assert.equal(Tides.laMidnight('2026-12-01').toISOString(), '2026-12-01T08:00:00.000Z');
  for (const iso of ['2026-11-01', '2027-03-14', '2030-07-04']) {
    const d = E.day('9446969', iso);
    assert.ok(d.length >= 3 && d.length <= 5, iso + ': ' + d.length + ' tides');
    d.forEach(x => assert.equal(Tides.laParts(x.at).date, iso));
  }
});

test('now: a level and a direction; the direction follows the curve', () => {
  const day = E.day('9447130', '2026-10-26');
  const lowToHigh = new Date((day[1].at.getTime() + day[2].at.getTime()) / 2);
  assert.equal(E.now('9447130', lowToHigh).rising, true);
  const highToLow = new Date((day[2].at.getTime() + day[3].at.getTime()) / 2);
  assert.equal(E.now('9447130', highToLow).rising, false);
  assert.equal(E.curve('9447130', '2026-10-26').length, 97);
});

test('the vendored engine is the unchanged MIT package, wrapped; the constants file is generated', () => {
  const src = fs.readFileSync(path.join(__dirname, '..', 'tide-predictor.js'), 'utf8');
  assert.match(src.split('\n')[0], /Generated by scripts\/vendor_tide_predictor\.py; Generated, do not edit\./);
  assert.match(src, /@neaps\/tide-predictor 0\.11\.0, .*MIT licence/);
  const harm = fs.readFileSync(path.join(__dirname, '..', 'tide-harmonics.js'), 'utf8');
  assert.match(harm.split('\n')[0], /Generated by scripts\/build_tide_harmonics\.py on \d{4}-\d{2}-\d{2}; Generated, do not edit\./);
});
