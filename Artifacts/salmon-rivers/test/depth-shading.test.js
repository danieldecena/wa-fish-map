test('depth shading eases down when a raster pixel gets big, and holds: it is soft, never switched off', () => {
  const fn = html.slice(html.indexOf('var SHADE_SOFT'), html.indexOf('function shadeTick'));
  const shadeFactor = new (require('node:vm').Script)('(function () { ' + fn + ' return shadeFactor; })')
    .runInNewContext()();
  assert.equal(shadeFactor(1), 1);
  assert.equal(shadeFactor(2.5), 1);
  assert.ok(Math.abs(shadeFactor(3.25) - 0.8) < 1e-9);
  assert.ok(Math.abs(shadeFactor(4) - 0.6) < 1e-9);
  assert.equal(shadeFactor(9), 0.6, 'it holds past the floor');
  // The closest zoom is 90 times the whole-state fit (limits()). On a 1280 by 800 window that is about 3.7 CSS pixels per raster pixel,
  // so a wide screen at the closest zoom is in the eased range; a phone (390 wide) stays under the full-strength limit.
  const pxUnits = Math.max(S.tiles[0].w / S.tiles[0].px[0], S.tiles[0].h / S.tiles[0].px[1]);
  const [x0, y0] = G.bounds.state[0], [x1, y1] = G.bounds.state[1];
  const closest = (W, H) => pxUnits * Math.min(W / (x1 - x0), H / (y1 - y0)) * 90;
  assert.ok(closest(1280, 800) > 2.5 && closest(1280, 800) < 4.2, `${closest(1280, 800).toFixed(2)} CSS px on a laptop`);
  assert.ok(closest(390, 844) < 2.5, `${closest(390, 844).toFixed(2)} CSS px on a phone`);
});
