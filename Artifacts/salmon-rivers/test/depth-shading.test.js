test('depth-shading.js: the whole file stays under 1.5 MB, with tiles of image data URIs', () => {
  assert.ok(Buffer.byteLength(src) < 1500000, `file is ${Buffer.byteLength(src)} bytes`);
  assert.ok(S.tiles.length >= 20 && S.tiles.length <= 200, `${S.tiles.length} tiles`);
  S.tiles.forEach((t, i) => {
    assert.deepEqual(Object.keys(t).sort(), ['h', 'px', 'uri', 'w', 'x', 'y'], `tile ${i}`);
    assert.match(t.uri, /^data:image\/webp;base64,[A-Za-z0-9+/=]+$/, `tile ${i} is an inline WebP`);
    const b = Buffer.from(t.uri.split(',')[1], 'base64');
    assert.equal(b.slice(0, 4).toString(), 'RIFF', `tile ${i} RIFF`);
    assert.equal(b.slice(8, 12).toString(), 'WEBP', `tile ${i} WEBP`);
    assert.ok(b.length < 40000, `tile ${i} is ${b.length} bytes`);
    assert.ok(t.px[0] >= 64 && t.px[0] <= 1024 && t.px[1] >= 64 && t.px[1] <= 1024, `tile ${i} pixel size`);
  });
});

test('depth-shading.js: every tile sits inside the state box and over Puget Sound, and the tiles share one size', () => {
  const sb = G.bounds.state;
  const w0 = S.tiles[0].w, h0 = S.tiles[0].h;
  S.tiles.forEach((t, i) => {
    assert.ok(t.x >= sb[0][0] && t.y >= sb[0][1] && t.x + t.w <= sb[1][0] && t.y + t.h <= sb[1][1], `tile ${i} inside the state box`);
    const [w, n] = unproj(t.x, t.y), [e, s] = unproj(t.x + t.w, t.y + t.h);
    assert.ok(w > -123.3 && e < -122.0 && s > 46.9 && n < 48.6, `tile ${i} is Puget Sound: lon ${w.toFixed(2)}..${e.toFixed(2)} lat ${s.toFixed(2)}..${n.toFixed(2)}`);
    assert.ok(Math.abs(t.w - w0) < 1e-3 && Math.abs(t.h - h0) < 1e-3, `tile ${i} same size`);
  });
});

test('depth-shading.js: tiles run one pixel into their neighbours, so no seam can open between them', () => {
  const t = S.tiles[0], sx = t.w * (t.px[0] - 1) / t.px[0], sy = t.h * (t.px[1] - 1) / t.px[1];
  const x0 = Math.min(...S.tiles.map(q => q.x)), y0 = Math.min(...S.tiles.map(q => q.y));
  S.tiles.forEach((q, i) => {
    assert.ok(Math.abs((q.x - x0) / sx - Math.round((q.x - x0) / sx)) < 0.01, `tile ${i} x is on the tile grid`);
    assert.ok(Math.abs((q.y - y0) / sy - Math.round((q.y - y0) / sy)) < 0.01, `tile ${i} y is on the tile grid`);
  });
  assert.ok(t.w > sx && t.h > sy, 'one pixel wider and taller than the grid step: it overlaps the next tile');
  // Each tile has a neighbour to its east or south, or is on an edge of the covered region: no two tiles overlap by more than that pixel.
  S.tiles.forEach((q, i) => S.tiles.slice(i + 1).forEach(o => {
    const ox = Math.min(q.x + q.w, o.x + o.w) - Math.max(q.x, o.x), oy = Math.min(q.y + q.h, o.y + o.h) - Math.max(q.y, o.y);
    if (ox > 0 && oy > 0) assert.ok(ox < q.w - sx + 1e-3 || oy < q.h - sy + 1e-3, 'overlap is one pixel');
  }));
});

