test('depth-shading.js: depth ramp stays calm blue: nothing red, orange, amber or yellow, no stop near the rating blue', () => {
  // The detector first: it must reject the four rating colours (a known-bad input) and accept the ramp (the known-good one).
  const rgb = h => [1, 3, 5].map(i => parseInt(h.slice(i, i + 2), 16));
  const hue = ([r, g, b]) => {
    r /= 255; g /= 255; b /= 255;
    const mx = Math.max(r, g, b), mn = Math.min(r, g, b), d = mx - mn;
    if (!d) return 0;
    const h = mx === r ? ((g - b) / d) % 6 : mx === g ? (b - r) / d + 2 : (r - g) / d + 4;
    return (h * 60 + 360) % 360;
  };
  const calm = c => hue(c) >= 185 && hue(c) <= 235 && Math.hypot(c[0] - 0, c[1] - 136, c[2] - 255) > 100;
  ['#ff383c', '#ff8d28', '#ffcc00', '#0088ff'].forEach(h => assert.ok(!calm(rgb(h)), `${h} is rejected`));
  assert.ok(S.ramp.length >= 6);
  S.ramp.forEach(([ft, h]) => assert.ok(calm(rgb(h)), `ramp stop ${ft} ft ${h}`));
  const lum = S.ramp.map(([, h]) => rgb(h).reduce((a, b) => a + b, 0));
  assert.deepEqual(lum, lum.slice().sort((a, b) => b - a), 'darker with depth');
  assert.deepEqual(S.ramp.map(s => s[0]), S.ramp.map(s => s[0]).slice().sort((a, b) => a - b));
  // Never a rating colour: the ramp does not reuse a CSS colour token of the rating ramp.
  ['--prime', '--good', '--fair', '--slow'].forEach(tok => {
    const m = new RegExp(tok + ':\\s*(#[0-9a-f]{6})', 'i').exec(html);
    assert.ok(m && !S.ramp.some(([, h]) => h.toLowerCase() === m[1].toLowerCase()), tok);
  });
});

