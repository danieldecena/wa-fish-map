#!/usr/bin/env python3
"""Write Artifacts/salmon-rivers/river-rules.js, the river sheets' Rules section,
from Artifacts/salmon-rivers/rules/river-rules.json.

    build_river_rules.py            build river-rules.js, print the report
    build_river_rules.py --check    build nothing, exit 1 on any error

river-rules.json is hand-maintained: WDFW's rules for the nine report rivers in
reports.js, each row read from WDFW's pamphlet or an emergency rule (the sources
are in docs/research/, never on the page). The web page only; the iOS app keeps
its guidance-not-regulation stance and never reads this.

Errors stop the build: a water id that is not a reports.js site, an unknown
species, empty or over-long text, text with a link or the word "open" (the page
never says a fishery is open in its own voice), a checked or through date that
is not a real day, a checked date in the future, a row that ends before it was
checked. A water with no rows is left out; the sheet then shows no Rules section.
"""

import argparse
import datetime
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "Artifacts" / "salmon-rivers" / "rules" / "river-rules.json"
OUT = ROOT / "Artifacts" / "salmon-rivers" / "river-rules.js"
REPORTS = ROOT / "Artifacts" / "salmon-rivers" / "reports.js"

SPECIES = ("Coho Salmon", "Chinook Salmon", "All salmon")
ROW_KEYS = {"species", "stretch", "text", "release", "through"}
MAX_TEXT = 240

HEADER = "/* Generated by scripts/build_river_rules.py from rules/river-rules.json; do not edit by hand. */\n"
TEMPLATE = """(function (root, factory) {
  if (typeof module === 'object' && module.exports) module.exports = factory();
  else root.RIVER_RULES = factory();
})(typeof self !== 'undefined' ? self : this, function () {
  'use strict';

  /* WDFW's rules for the report rivers, as text. Display only: nothing here colours a pin, a river or a rating. */
  var ROWS = __ROWS__;
  /* The rows for one water that still apply on `today` (YYYY-MM-DD): a row is dropped after its `through` day. */
  function forWater(id, today) {
    return ROWS.filter(function (r) { return r.id === id && r.through >= today; });
  }
  return { ROWS: ROWS, forWater: forWater };
});
"""


def report_ids(text):
    """The site ids in reports.js SITES, read from the source."""
    return set(re.findall(r"\{ id: '([a-z]+)', name:", text))


def day(text, where, errors):
    try:
        return datetime.date.fromisoformat(text)
    except (TypeError, ValueError):
        errors.append(f"{where}: {text!r} is not a YYYY-MM-DD date")
        return None


def build_rows(src, ids, today):
    """Return (rows, errors) for a parsed river-rules.json."""
    errors, rows = [], []
    waters = src.get("waters")
    if not isinstance(waters, dict) or not waters:
        return [], ["waters must be an object with at least one water"]
    for wid, w in waters.items():
        where = f"water {wid}"
        if wid not in ids:
            errors.append(f"{where}: not a site id in reports.js")
        checked = day(w.get("checked"), f"{where} checked", errors)
        if checked and checked > today:
            errors.append(f"{where}: checked {w['checked']} is in the future")
        wrows = w.get("rows")
        if not isinstance(wrows, list) or not wrows:
            errors.append(
                f"{where}: needs at least one row (leave the water out to show no Rules section)"
            )
            continue
        for i, r in enumerate(wrows):
            at = f"{where} row {i + 1}"
            extra = set(r) - ROW_KEYS
            if extra:
                errors.append(f"{at}: unknown keys {sorted(extra)}")
            if r.get("species") not in SPECIES:
                errors.append(f"{at}: species {r.get('species')!r} not in {SPECIES}")
            text = r.get("text")
            if not isinstance(text, str) or not text.strip():
                errors.append(f"{at}: text is empty")
                text = ""
            elif len(text) > MAX_TEXT:
                errors.append(f"{at}: text is {len(text)} characters, over {MAX_TEXT}")
            if re.search(r"https?:|www\.", text):
                errors.append(
                    f"{at}: text carries a link; sources stay out of the sheet"
                )
            if re.search(r"\bopen(s|ed|ing)?\b", text, re.I):
                errors.append(f"{at}: text says open; say what WDFW's rule says")
            stretch = r.get("stretch")
            if stretch is not None and (
                not isinstance(stretch, str) or not stretch.strip()
            ):
                errors.append(f"{at}: stretch must be a non-empty string or left out")
            if "release" in r and not isinstance(r["release"], bool):
                errors.append(f"{at}: release must be true or false")
            through = day(r.get("through"), f"{at} through", errors)
            if through and checked and through < checked:
                errors.append(
                    f"{at}: ends {r['through']} before it was checked {w.get('checked')}"
                )
            rows.append(
                {
                    "id": wid,
                    "species": r.get("species"),
                    "stretch": stretch,
                    "text": text,
                    "release": bool(r.get("release", False)),
                    "through": r.get("through"),
                    "checked": w.get("checked"),
                }
            )
    return rows, errors


def render(rows):
    body = json.dumps(rows, indent=2, ensure_ascii=False).replace("\n", "\n  ")
    return HEADER + TEMPLATE.replace("__ROWS__", body)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    src = json.loads(SRC.read_text())
    ids = report_ids(REPORTS.read_text())
    rows, errors = build_rows(src, ids, datetime.date.today())
    if errors:
        for e in errors:
            print("error:", e, file=sys.stderr)
        sys.exit(1)

    per = {}
    for r in rows:
        per[r["id"]] = per.get(r["id"], 0) + 1
    for wid in sorted(ids):
        print(
            f"{wid}: {per.get(wid, 0)} rows"
            if wid in per
            else f"{wid}: no rows (no Rules section)"
        )

    text = render(rows)
    if args.check:
        have = OUT.read_text() if OUT.exists() else None
        if have != text:
            print(
                "error: river-rules.js is stale: rerun scripts/build_river_rules.py",
                file=sys.stderr,
            )
            sys.exit(1)
        print("river-rules.js matches river-rules.json")
        return
    OUT.write_text(text)
    print("wrote", OUT.relative_to(ROOT), OUT.stat().st_size, "bytes")


if __name__ == "__main__":
    main()
