#!/usr/bin/env python3
"""Write Artifacts/salmon-rivers/counts.js from the salmon table.

    build_salmon_counts.py

Reads the `board` view of ~/database/salmon-rivers/salmon.db (built by
build_salmon_db.py) and keeps, for each page water, only its newest report week
that has salmon rows. These are WDFW creel counts, not ratings: nothing here
feeds the rating logic in reports.js. A blank in the table means the report did
not state the number; it stays null here, never 0.

The Lower Columbia is one page water made of many WDFW sections. Its rows are
combined per species by summing Kept and Released over the sections that
reported that week. Anglers is a total for the section, repeated on each of its
species rows in the table, so it is summed once per section, not once per row.
"""

import datetime
import json
import re
import sqlite3
import sys
from pathlib import Path

DB = Path.home() / "database" / "salmon-rivers" / "salmon.db"
OUT = (
    Path(__file__).resolve().parent.parent / "Artifacts" / "salmon-rivers" / "counts.js"
)

# page water id -> [(board River, section label shown on the page)]; "*" rows
# are all matched by prefix and combined.
WATERS = {
    "cowlitz": [
        ("Cowlitz, above I-5 Br", "Above I-5 Br"),
        ("Cowlitz, below I-5 Br", "Below I-5 Br"),
    ],
    "columbia": "Lower Columbia, Sec ",
    "lewis": [("Lewis", None)],
    "wind": [("Wind", None)],
    "drano": [("Drano Lake", None)],
    "klickitat": [
        ("Klickitat, below Fisher Hill Br", "Below Fisher Hill Br"),
        ("Klickitat, above Fisher Hill Br", "Above Fisher Hill Br"),
    ],
}
COMBINED_LABEL = "All sections combined"

# Species names exactly as the table writes them, in display order. Steelhead,
# sockeye, sturgeon and "Jack (species not stated)" are deliberately absent.
SPECIES = [
    "Coho Salmon",
    "Coho Salmon (jack)",
    "Chinook Salmon",
    "Chinook Salmon (jack)",
]

MONTHS = [
    "Jan",
    "Feb",
    "Mar",
    "Apr",
    "May",
    "Jun",
    "Jul",
    "Aug",
    "Sep",
    "Oct",
    "Nov",
    "Dec",
]

HEADER = """/* Generated by scripts/build_salmon_counts.py from the salmon table; do not edit by hand. */
(function (root, factory) {
  if (typeof module === 'object' && module.exports) module.exports = factory();
  else root.Counts = factory();
})(typeof self !== 'undefined' ? self : this, function () {
  'use strict';
  /* WDFW weekly creel counts: the newest report week with salmon rows, per water. Counts, not ratings. */
  var WATERS = %s;
  return { WATERS: WATERS, forWater: function (id) { return WATERS[id] || null; } };
});
"""


def parse_week(week, url):
    """'2026-10-05 to 10-11' -> (start, end) dates. The year is checked against the PDF name."""
    m = re.fullmatch(r"(\d{4})-(\d\d)-(\d\d) to (\d\d)-(\d\d)", week)
    if not m:
        sys.exit(f"unexpected Week text {week!r}")
    y, m1, d1, m2, d2 = map(int, m.groups())
    start = datetime.date(y, m1, d1)
    end = datetime.date(y + (m2 < m1), m2, d2)
    if not 0 <= (end - start).days <= 6:
        sys.exit(f"week {week!r} spans {(end - start).days} days")
    stem = url.rsplit("/", 1)[-1]
    if not re.search(rf"-{end.year}(_\d+)?\.pdf$", stem):
        sys.exit(f"week end {end} does not match the year in {stem}")
    return start, end


def day(d):
    return f"{MONTHS[d.month - 1]} {d.day}"


def total(values):
    got = [v for v in values if v is not None]
    return sum(got) if got else None


def build():
    con = sqlite3.connect(f"file:{DB}?mode=ro", uri=True)
    board = con.execute(
        "SELECT River, Species, Week, Anglers, Kept, Released, Source FROM board"
    ).fetchall()
    if not board:
        sys.exit("the board view returned no rows")
    out = {}
    for wid, spec in WATERS.items():
        if isinstance(spec, str):
            rivers = {r for r, *_ in board if r.startswith(spec)}
            sections = {r: None for r in rivers}
            combined = True
        else:
            sections = dict(spec)
            combined = False
        mine = [row for row in board if row[0] in sections]
        newest_any = max((r[2] for r in mine), default=None)
        have = {r[2] for r in mine if r[1] in SPECIES}
        if not have:
            print(f"{wid}: no salmon rows, left out", file=sys.stderr)
            continue
        # Weeks sort as text: 'YYYY-MM-DD to MM-DD' starts with the start date.
        week = max(have)
        if newest_any != week:
            print(
                f"{wid}: newer week {newest_any} has no salmon rows; showing {week}",
                file=sys.stderr,
            )
        wk = [r for r in mine if r[2] == week]
        bad = [r[0] for r in wk if r[1] == "(not parsed)"]
        if bad:
            sys.exit(f"{wid} {week}: unparsed entries {bad}; refusing a partial week")
        urls = {r[6] for r in wk}
        if len(urls) != 1:
            sys.exit(f"{wid} {week}: {len(urls)} source URLs")
        url = urls.pop()
        start, end = parse_week(week, url)

        # Anglers is per section: take it once per section and check the rows agree.
        angl = {}
        for r in wk:
            if r[0] in angl and angl[r[0]] != r[3]:
                sys.exit(f"{wid} {week}: {r[0]} has two Anglers values")
            angl[r[0]] = r[3]

        rows = []
        if combined:
            reported = sorted(
                {r[0] for r in wk},
                key=lambda s: int(re.search(r"Sec (\d+)", s).group(1)),
            )
            for sp in SPECIES:
                sel = [r for r in wk if r[1] == sp]
                if sel:
                    rows.append(
                        {
                            "section": COMBINED_LABEL,
                            "species": sp,
                            "anglers": total(angl.values()),
                            "kept": total(r[4] for r in sel),
                            "released": total(r[5] for r in sel),
                        }
                    )
            nums = [re.search(r"Sec (\d+)", s).group(1) for s in reported]
            note = "Sections that reported: " + ", ".join(nums) + "."
        else:
            for river, label in sections.items():
                for sp in SPECIES:
                    for r in wk:
                        if r[0] == river and r[1] == sp:
                            rows.append(
                                {
                                    "section": label,
                                    "species": sp,
                                    "anglers": r[3],
                                    "kept": r[4],
                                    "released": r[5],
                                }
                            )
            note = None
        if not rows:
            print(f"{wid}: {week} has no salmon rows, left out", file=sys.stderr)
            continue
        out[wid] = {
            "week": f"{day(start)} to {day(end)}",
            "weekStart": start.isoformat(),
            "weekEnd": end.isoformat(),
            "source": url,
            "note": note,
            "rows": rows,
        }
    return out


if __name__ == "__main__":
    data = build()
    body = json.dumps(data, indent=2, ensure_ascii=True)
    OUT.write_text(HEADER % body.replace("\n", "\n  "))
    for wid, w in data.items():
        print(wid, w["weekEnd"], len(w["rows"]), "rows")
