#!/usr/bin/env python3
"""Write Artifacts/salmon-rivers/tide-harmonics.js from NOAA CO-OPS station metadata.

    build_tide_harmonics.py            # fetch and write
    build_tide_harmonics.py --check    # validate the existing file, no network

Generated file: do not hand-edit. The page computes tide predictions itself
(tide-predictor.js, the Neaps engine) from these constants, so it needs no
network and never runs out of dates. For every station in build_tides.STATIONS:

- a harmonic station gets NOAA's constituents (amplitude in feet, phase_GMT in
  degrees, speed) and `msl`, mean sea level above MLLW, so predicted heights
  read against MLLW like NOAA's own predictions;
- a subordinate station (NOAA publishes no constituents for it) gets its
  reference station and NOAA's published high/low corrections.

Fails loudly on an HTTP error, a station with neither, or a reference station
that is not itself harmonic. Predictions, not observations; never a rating.
"""

import argparse
import datetime
import json
import sys
import urllib.request
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from build_tides import STATIONS, write_atomic  # noqa: E402

OUT = Path(__file__).resolve().parent.parent / "Artifacts" / "salmon-rivers" / "tide-harmonics.js"
MD = "https://api.tidesandcurrents.noaa.gov/mdapi/prod/webapi/stations/{id}/{what}.json"
HEADER = (
    "/* Generated by scripts/build_tide_harmonics.py on {generated}; Generated, do not edit.\n"
    " * NOAA CO-OPS harmonic constituents (feet, phase_GMT) and subordinate-station corrections. Predictions, not observations. */\n"
)


class BuildError(Exception):
    pass


def get(station_id, what, query="units=english"):
    url = MD.format(id=station_id, what=what) + ("?" + query if query else "")
    with urllib.request.urlopen(url, timeout=60) as r:
        return json.load(r)


def station_entry(station_id, fetcher=get):
    harcon = fetcher(station_id, "harcon").get("HarmonicConstituents") or []
    if harcon:
        datums = {d["name"]: d["value"] for d in fetcher(station_id, "datums").get("datums", [])}
        if "MSL" not in datums or "MLLW" not in datums:
            raise BuildError(f"{station_id}: no MSL/MLLW datum")
        return {
            "id": station_id,
            "msl": round(datums["MSL"] - datums["MLLW"], 3),
            "harmonics": [
                {"name": c["name"], "amplitude": c["amplitude"], "phase": c["phase_GMT"], "speed": c["speed"]}
                for c in harcon if c["amplitude"] > 0
            ],
        }
    off = fetcher(station_id, "tidepredoffsets", "")
    if not off.get("refStationId"):
        raise BuildError(f"{station_id}: neither constituents nor subordinate offsets")
    kind = "ratio" if off.get("heightAdjustedType") == "R" else "fixed"
    return {
        "id": station_id,
        "ref": off["refStationId"],
        "offsets": {
            "height": {"high": off["heightOffsetHighTide"], "low": off["heightOffsetLowTide"], "type": kind},
            "time": {"high": off["timeOffsetHighTide"], "low": off["timeOffsetLowTide"]},
        },
    }


def build(fetcher=get):
    stations = []
    for sid, name, lat, lon in STATIONS:
        stations.append(dict(station_entry(sid, fetcher), name=name, lat=lat, lon=lon))
    harmonic = {s["id"] for s in stations if "harmonics" in s}
    extra = []
    for s in stations:
        # A subordinate station's reference may sit outside the bundle; fetch it so the page can predict from it.
        if "ref" in s and s["ref"] not in harmonic:
            ref = station_entry(s["ref"], fetcher)
            if "harmonics" not in ref:
                raise BuildError(f"{s['id']}: reference {s['ref']} is not harmonic")
            # Reached only through a subordinate station: never offered as a nearest station itself.
            extra.append(dict(ref, refOnly=True))
            harmonic.add(ref["id"])
    return {"generated": datetime.date.today().isoformat(), "stations": stations + extra}


def render(bundle):
    return HEADER.format(generated=bundle["generated"]) + "window.TIDE_HARMONICS=" + json.dumps(bundle, separators=(",", ":")) + ";\n"


def validate(bundle):
    ids = {s["id"] for s in bundle["stations"]}
    for s in bundle["stations"]:
        if "harmonics" in s:
            if len(s["harmonics"]) < 8 or not any(c["name"] == "M2" for c in s["harmonics"]):
                raise BuildError(f"{s['id']}: too few constituents or no M2")
        elif s.get("ref") not in ids:
            raise BuildError(f"{s['id']}: reference {s.get('ref')} missing")
    for sid, *_ in STATIONS:
        if sid not in ids:
            raise BuildError(f"{sid}: missing")


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    if a.check:
        text = OUT.read_text()
        bundle = json.loads(text.split("window.TIDE_HARMONICS=", 1)[1].rstrip().rstrip(";"))
        validate(bundle)
        print(f"ok: {len(bundle['stations'])} stations")
        return 0
    bundle = build()
    validate(bundle)
    write_atomic(OUT, render(bundle))
    print(f"wrote {OUT.name}: {len(bundle['stations'])} stations")
    return 0


if __name__ == "__main__":
    sys.exit(main())
