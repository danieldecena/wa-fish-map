#!/usr/bin/env python3
"""Write Artifacts/salmon-rivers/tide-predictor.js from a downloaded @neaps/tide-predictor.

    npm pack @neaps/tide-predictor@0.11.0      # in an empty scratch folder; unpack the .tgz there
    vendor_tide_predictor.py <unpacked>/package/dist/index.js

Generated file: do not hand-edit. The page has no build step, so the package's
single ES module is wrapped as a classic script: its one `export { ... }` line
becomes `window.TidePredictor` (or `module.exports` in Node, for the tests).
Nothing else in the code changes. MIT licensed (Kevin Miller and Neaps
contributors); the licence line and the source sha256 go in the header.
"""

import hashlib
import json
import re
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "Artifacts" / "salmon-rivers" / "tide-predictor.js"
VERSION = "0.11.0"


def main(argv):
    src = Path(argv[1])
    pkg = json.loads((src.parent.parent / "package.json").read_text())
    if pkg["name"] != "@neaps/tide-predictor" or pkg["version"] != VERSION or pkg["license"] != "MIT":
        raise SystemExit(f"expected @neaps/tide-predictor {VERSION} (MIT), got {pkg['name']} {pkg['version']} ({pkg['license']})")
    code = src.read_text()
    exports = re.findall(r"^export \{[^}]*\};\s*$", code, re.M)
    if len(exports) != 1 or re.search(r"^import\s", code, re.M) or re.search(r"\bfetch\(|XMLHttpRequest", code):
        raise SystemExit("the module no longer has exactly one export line and no imports or network calls; review it")
    body = code.replace(exports[0], "").rstrip()
    sha = hashlib.sha256(code.encode()).hexdigest()
    out = (
        f"/* Generated by scripts/vendor_tide_predictor.py; Generated, do not edit.\n"
        f" * @neaps/tide-predictor {VERSION}, https://github.com/openwatersio/neaps, MIT licence, (c) Kevin Miller and Neaps contributors.\n"
        f" * Source dist/index.js sha256 {sha}. Wrapped as a classic script; the code below is unchanged. */\n"
        "(function (root) {\n'use strict';\n"
        + body
        + "\nvar api = { createTidePredictor: createTidePredictor };\n"
        "if (typeof module === 'object' && module.exports) module.exports = api; else root.TidePredictor = api;\n"
        "})(typeof self !== 'undefined' ? self : this);\n"
    )
    OUT.write_text(out)
    print(f"wrote {OUT.name} ({len(out)} bytes)")


if __name__ == "__main__":
    main(sys.argv)
