"""Tests for the validation and output of build_river_rules.py.

/opt/homebrew/bin/python3 -m unittest discover -s scripts -p "test_build_river_rules.py"
"""

import copy
import datetime
import importlib.util
import sys
import unittest
from pathlib import Path

spec = importlib.util.spec_from_file_location(
    "brr", Path(__file__).resolve().parent / "build_river_rules.py"
)
brr = importlib.util.module_from_spec(spec)
sys.modules["brr"] = brr
spec.loader.exec_module(brr)

TODAY = datetime.date(2026, 10, 29)
IDS = {"cowlitz", "skagit"}
GOOD = {
    "waters": {
        "cowlitz": {
            "checked": "2026-10-29",
            "rows": [
                {
                    "species": "Coho Salmon",
                    "stretch": "Mouth to the dam",
                    "text": "Aug 1 to Dec 31: 6 salmon a day, no more than 3 adults.",
                    "through": "2026-12-31",
                },
                {
                    "species": "Chinook Salmon",
                    "text": "Release all Chinook.",
                    "release": True,
                    "through": "2026-12-31",
                },
            ],
        }
    }
}


def build(src):
    return brr.build_rows(src, IDS, TODAY)


def broken(mutate):
    src = copy.deepcopy(GOOD)
    mutate(src["waters"]["cowlitz"])
    return build(src)[1]


class KnownGood(unittest.TestCase):
    def test_a_good_file_builds_without_errors(self):
        rows, errors = build(GOOD)
        self.assertEqual(errors, [])
        self.assertEqual(
            [r["species"] for r in rows], ["Coho Salmon", "Chinook Salmon"]
        )
        self.assertIsNone(rows[1]["stretch"])
        self.assertTrue(rows[1]["release"])
        self.assertFalse(rows[0]["release"])
        self.assertEqual(rows[0]["checked"], "2026-10-29")

    def test_the_output_carries_the_header_and_every_row(self):
        text = brr.render(build(GOOD)[0])
        self.assertTrue(text.startswith("/* Generated by scripts/build_river_rules.py"))
        self.assertIn("do not edit by hand", text.splitlines()[0])
        self.assertEqual(text.count('"id": "cowlitz"'), 2)

    def test_report_ids_reads_the_real_reports_file(self):
        ids = brr.report_ids(brr.REPORTS.read_text())
        self.assertEqual(len(ids), 9)
        self.assertIn("drano", ids)


class KnownBad(unittest.TestCase):
    def test_an_unknown_water_is_refused(self):
        src = copy.deepcopy(GOOD)
        src["waters"]["nowhere"] = src["waters"].pop("cowlitz")
        self.assertTrue(any("not a site id" in e for e in build(src)[1]))

    def test_an_unknown_species_is_refused(self):
        errors = broken(lambda w: w["rows"][0].update(species="Steelhead"))
        self.assertTrue(any("species" in e for e in errors))

    def test_empty_text_is_refused(self):
        errors = broken(lambda w: w["rows"][0].update(text="  "))
        self.assertTrue(any("text is empty" in e for e in errors))

    def test_a_link_in_the_text_is_refused(self):
        errors = broken(
            lambda w: w["rows"][0].update(text="See https://wdfw.wa.gov/ for limits.")
        )
        self.assertTrue(any("link" in e for e in errors))

    def test_the_word_open_is_refused(self):
        errors = broken(
            lambda w: w["rows"][0].update(text="The river is open for coho.")
        )
        self.assertTrue(any("says open" in e for e in errors))

    def test_a_bad_date_is_refused(self):
        errors = broken(lambda w: w.update(checked="2026-13-40"))
        self.assertTrue(any("not a YYYY-MM-DD date" in e for e in errors))

    def test_a_checked_date_in_the_future_is_refused(self):
        errors = broken(lambda w: w.update(checked="2026-11-30"))
        self.assertTrue(any("in the future" in e for e in errors))

    def test_a_row_that_ends_before_it_was_checked_is_refused(self):
        errors = broken(lambda w: w["rows"][0].update(through="2026-10-01"))
        self.assertTrue(any("before it was checked" in e for e in errors))

    def test_an_unknown_key_is_refused(self):
        errors = broken(lambda w: w["rows"][0].update(source="x"))
        self.assertTrue(any("unknown keys" in e for e in errors))

    def test_a_water_with_no_rows_is_refused(self):
        errors = broken(lambda w: w.update(rows=[]))
        self.assertTrue(any("at least one row" in e for e in errors))

    def test_the_real_source_passes(self):
        import json

        src = json.loads(brr.SRC.read_text())
        ids = brr.report_ids(brr.REPORTS.read_text())
        self.assertEqual(brr.build_rows(src, ids, TODAY)[1], [])


if __name__ == "__main__":
    unittest.main()
