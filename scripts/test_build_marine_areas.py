"""Tests for scripts/build_marine_areas.py: a tiny known-good source, deliberately broken
ones, and the committed marine-areas.js against typical.js. Run:

    /opt/homebrew/bin/python3 -m unittest discover -s scripts -p "test_build_marine_areas.py"
"""

import json
import re
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import build_marine_areas as m

GEO = (
    'window.GEO = {"proj":{"kx":70.0,"k":100.0,"lat0":49.0,"lon0":-125.0},'
    '"bounds":{"state":[[0,0],[100,100]],"sw":[[0,0],[1,1]]}};'
)
TYPICAL = (
    'return {"generated":"x","areas":{"A":{"title":"Alpha Sound","wac":"w"},'
    '"B":{"title":"Beta Bay","wac":"w"}},"basemap":{"water":""}};'
)


def square(lon, lat, size):
    """A closed lon/lat ring, size in degrees."""
    return [
        [lon, lat],
        [lon + size, lat],
        [lon + size, lat + size],
        [lon, lat + size],
        [lon, lat],
    ]


def feature(name, title, polys, kind="Polygon"):
    coords = polys if kind == "Polygon" else [polys]
    return {
        "type": "Feature",
        "properties": {"AreaName": name, "AreaTitle": title},
        "geometry": {"type": kind, "coordinates": coords},
    }


def good_source():
    # A: 0.2 degree square (14 x 20 map units) with a 0.1 degree island hole and a sliver islet.
    a = [
        square(-124.5, 48.0, 0.2),
        square(-124.45, 48.05, 0.1),
        square(-124.3, 48.15, 0.001),
    ]
    b = [square(-124.0, 48.5, 0.1)]
    oregon = [square(-124.0, 45.0, 0.1)]
    return {
        "type": "FeatureCollection",
        "features": [
            feature("A", "Alpha Sound", a),
            feature("B", "Beta Bay", b),
            feature("Oregon", "North of Falcon", oregon),
        ],
    }


class Tmp(unittest.TestCase):
    def setUp(self):
        self.dir = tempfile.TemporaryDirectory()
        self.addCleanup(self.dir.cleanup)
        d = Path(self.dir.name)
        (d / "geo.js").write_text(GEO)
        (d / "typical.js").write_text(TYPICAL)
        self.saved = (m.GEO, m.TYPICAL, m.OUT)
        m.GEO, m.TYPICAL, m.OUT = d / "geo.js", d / "typical.js", d / "marine-areas.js"
        self.addCleanup(
            lambda: (
                setattr(m, "GEO", self.saved[0])
                or setattr(m, "TYPICAL", self.saved[1])
                or setattr(m, "OUT", self.saved[2])
            )
        )
        self.src = d / "src.geojson"

    def write(self, obj):
        self.src.write_text(json.dumps(obj))


class KnownGood(Tmp):
    def test_builds_the_known_good_input(self):
        self.write(good_source())
        errors = []
        entries, report = m.build(self.src, errors)
        self.assertEqual(errors, [])
        self.assertEqual(
            list(entries), ["A", "B"], "Oregon is dropped; ids follow typical.js"
        )
        a = entries["A"]
        self.assertEqual(a["title"], "Alpha Sound")
        # Projection: x = (lon + 125) * 70, y = (49 - lat) * 100. The 0.2 degree square is 14 wide and 20 tall.
        self.assertEqual(a["bbox"], [[35.0, 80.0], [49.0, 100.0]])
        self.assertEqual(a["centroid"], [42.0, 90.0])
        # The outer ring and the island are kept, the 0.001 degree sliver is not.
        self.assertEqual(a["d"].count("M"), 2)
        self.assertEqual(a["d"].count("Z"), 2)
        self.assertEqual(report[0][1]["dropped"], 1)
        self.assertRegex(a["d"], r"^M[-\d. ]+Z")

    def test_render_then_check_round_trip(self):
        self.write(good_source())
        errors = []
        entries, _ = m.build(self.src, errors)
        text = m.render(entries)
        self.assertTrue(
            text.startswith(
                "/* Generated by scripts/build_marine_areas.py; do not edit by hand."
            )
        )
        self.assertEqual(m.parse_file(text), entries)
        check = []
        m.check_file(text, check)
        self.assertEqual(check, [])

    def test_cli_writes_then_check_passes_then_goes_stale(self):
        self.write(good_source())
        # A subprocess would read the real geo.js and typical.js, so call main() with the patched paths.
        argv = sys.argv
        try:
            sys.argv = ["x", "--src", str(self.src)]
            m.main()
            self.assertTrue(m.OUT.exists())
            sys.argv = ["x", "--src", str(self.src), "--check"]
            m.main()
            m.OUT.write_text(m.OUT.read_text().replace("Alpha Sound", "Alpha Sounds"))
            with self.assertRaises(SystemExit) as cm:
                m.main()
            self.assertEqual(cm.exception.code, 1, "a stale file fails --check")
        finally:
            sys.argv = argv

    def test_collinear_points_go_and_corners_stay(self):
        ring = [(0, 0), (5, 0.01), (10, 0), (10, 10), (0, 10)]
        out = m.simplify_ring(ring, 0.1)
        self.assertEqual(out, [(0, 0), (10, 0), (10, 10), (0, 10)])
        self.assertEqual(
            m.simplify_ring(ring, 0.0001), ring, "a tighter tolerance keeps the nudge"
        )

    def test_clip_cuts_to_the_window(self):
        out = m.clip_ring([(-10, 0), (10, 0), (10, 10), (-10, 10)], [[0, 0], [5, 5]])
        xs = [p[0] for p in out]
        ys = [p[1] for p in out]
        self.assertEqual((min(xs), max(xs), min(ys), max(ys)), (0, 5, 0, 5))


class Broken(Tmp):
    def errors(self, obj=None, raw=None):
        if raw is not None:
            self.src.write_text(raw)
        elif obj is not None:
            self.write(obj)
        errs = []
        m.build(self.src, errs)
        return errs

    def test_missing_source(self):
        self.assertTrue(any("cannot read" in e for e in self.errors()))

    def test_malformed_json(self):
        self.assertTrue(any("cannot read" in e for e in self.errors(raw="{not json")))

    def test_area_typical_does_not_have(self):
        src = good_source()
        src["features"].append(feature("C", "Gamma", [square(-124.0, 46.0, 0.1)]))
        self.assertTrue(
            any("area C that typical.js does not" in e for e in self.errors(src))
        )

    def test_area_typical_has_but_source_lacks(self):
        src = good_source()
        src["features"] = src["features"][:1]
        self.assertTrue(any("typical.js has area B" in e for e in self.errors(src)))

    def test_title_differs(self):
        src = good_source()
        src["features"][1]["properties"]["AreaTitle"] = "Beta Bays"
        self.assertTrue(any("differs from typical.js" in e for e in self.errors(src)))

    def test_only_slivers_left(self):
        src = good_source()
        src["features"][1] = feature("B", "Beta Bay", [square(-124.0, 48.5, 0.001)])
        self.assertTrue(any("area B: no ring left" in e for e in self.errors(src)))

    def test_feature_without_properties(self):
        src = good_source()
        del src["features"][0]["properties"]
        self.assertTrue(any("malformed" in e for e in self.errors(src)))

    def test_size_cap_and_wrong_shape_fail_the_file_check(self):
        errs = []
        m.check_file("not the generated file", errs)
        self.assertTrue(any("generated shape" in e for e in errs))
        self.write(good_source())
        entries, _ = m.build(self.src, [])
        text = m.render(entries)
        old = m.MAX_BYTES
        try:
            m.MAX_BYTES = 100
            errs = []
            m.check_file(text, errs)
            self.assertTrue(any("over 100" in e for e in errs))
        finally:
            m.MAX_BYTES = old
        errs = []
        m.check_file(text.replace('"B": {', '"Z": {'), errs)
        self.assertTrue(any("differ from typical.js" in e for e in errs))


class Committed(unittest.TestCase):
    """The file in the repo, against the real typical.js and geo.js."""

    def test_ids_equal_typical_areas_and_size_is_capped(self):
        text = m.OUT.read_text()
        data = m.parse_file(text)
        self.assertIsNotNone(data)
        self.assertEqual(set(data), set(m.typical_areas(m.TYPICAL.read_text())))
        self.assertLessEqual(len(text.encode()), m.MAX_BYTES)

    def test_bboxes_sit_inside_the_pan_window_and_land_areas_inside_the_state(self):
        sb = m.state_box(m.GEO.read_text())
        data = m.parse_file(m.OUT.read_text())
        for aid, e in data.items():
            (x0, y0), (x1, y1) = e["bbox"]
            self.assertLess(x0, x1)
            self.assertLess(y0, y1)
            self.assertGreaterEqual(x0, sb[0][0] - m.WINDOW_MARGIN - 0.01, aid)
            self.assertGreaterEqual(y0, sb[0][1] - m.WINDOW_MARGIN - 0.01, aid)
            self.assertLessEqual(x1, sb[1][0] + m.WINDOW_MARGIN + 0.01, aid)
            self.assertLessEqual(y1, sb[1][1] + m.WINDOW_MARGIN + 0.01, aid)
            self.assertTrue(
                x0 <= e["centroid"][0] <= x1 and y0 <= e["centroid"][1] <= y1, aid
            )
            if aid not in ("1", "2", "3", "4"):
                self.assertGreaterEqual(x0, sb[0][0], aid)
                self.assertLessEqual(x1, sb[1][0], aid)

    def test_every_path_is_closed_numbers(self):
        for aid, e in m.parse_file(m.OUT.read_text()).items():
            self.assertRegex(e["d"], r"^(M-?[\d.]+( -?[\d.]+)+Z)+$", aid)
            self.assertNotIn("nan", e["d"].lower())

    def test_check_without_the_source_says_so(self):
        r = subprocess.run(
            [
                sys.executable,
                str(Path(m.__file__)),
                "--check",
                "--src",
                "/nonexistent/marine-areas.geojson",
            ],
            capture_output=True,
            text=True,
            check=False,
        )
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertIn("not present", r.stderr)
        self.assertIn("staleness not checked", r.stdout)

    def test_check_fails_on_a_broken_file(self):
        with tempfile.TemporaryDirectory() as d:
            self.assertTrue(re.search(r"marine-areas", str(m.OUT)))
            old, argv = m.OUT, sys.argv
            try:
                bad = Path(d) / "marine-areas.js"
                bad.write_text("broken")
                m.OUT = bad
                with self.assertRaises(SystemExit) as cm:
                    sys.argv = ["x", "--check", "--src", "/nonexistent/x.geojson"]
                    m.main()
                self.assertEqual(cm.exception.code, 1)
            finally:
                m.OUT, sys.argv = old, argv


if __name__ == "__main__":
    unittest.main()
