#!/usr/bin/env python3
"""Write Artifacts/salmon-rivers/marine-areas.js: the WDFW marine area outlines the
map's water focus draws and fits.

    build_marine_areas.py [--src PATH]          build marine-areas.js, print the report
    build_marine_areas.py --check [--src PATH]  build nothing, exit 1 on any error

The source is WDFW's marine area layer (the GeoJSON `scripts/build_typical_sites.py`
caches in .cache/wdfw/, gitignored). Like the app (MapScope.filter) and the Typical
season snapshot, the North of Falcon "Oregon" polygon is dropped: Oregon regulates
it, so the map is Washington only. That leaves 16 areas, keyed by exactly the ids
typical.js uses for TypicalData.areas and site.area ("11", "2-2", "8-1" ...).

Each outline is projected into the page's map units with the constants in geo.js
(x = (lon - lon0) * kx, y = (lat0 - lat) * k), simplified with Douglas-Peucker, and
stripped of sliver rings (islets under MIN_RING map units across) before it is
written as one SVG path (all rings; the page fills it even-odd, so islands are holes).
`bbox` and `centroid` are measured on the outline clipped to the page's pan window
(the state box plus WINDOW_MARGIN units): the four ocean areas (1 to 4) run out to
-129 degrees, far past anywhere the map can be dragged, and the camera should fit the
coast, not the open ocean. The path itself is not clipped.

With --check the file on disk is validated (shape, ids equal typical.js areas, size cap,
header). If the source is present it is rebuilt and compared too, so a stale file fails;
if the source is absent that is said out loud and only the file is checked.

Errors stop the build: a missing or malformed source, an area id that typical.js does
not have (or the reverse), a title that differs from typical.js, an area with no ring
left, a file over MAX_BYTES.
"""

import argparse
import json
import math
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PAGE = ROOT / "Artifacts" / "salmon-rivers"
SRC = ROOT / ".cache" / "wdfw" / "marine-areas.geojson"
OUT = PAGE / "marine-areas.js"
GEO = PAGE / "geo.js"
TYPICAL = PAGE / "typical.js"

TOLERANCE = 0.1  # Douglas-Peucker, map units (about 110 m). WDFW's layer is already generalised to about 0.2.
MIN_RING = 1.5  # a ring whose bounding box is under this many map units across (about 1.7 km) is dropped
DECIMALS = 2
WINDOW_MARGIN = 12.0  # map units added to the state box to make the pan window
MAX_BYTES = 90_000
OREGON = "Oregon"

HEADER = (
    "/* Generated by scripts/build_marine_areas.py; do not edit by hand. WDFW marine area outlines in the page's map units (geo.js projection),\n"
    " * one SVG path per area (all rings, fill even-odd). bbox and centroid are measured on the outline clipped to the pan window. */\n"
)
TEMPLATE = """(function (root, factory) {
  if (typeof module === 'object' && module.exports) module.exports = factory();
  else root.MARINE_AREAS = factory();
})(typeof self !== 'undefined' ? self : this, function () {
  'use strict';
  return {
__BODY__
  };
});
"""


# ---- inputs ----------------------------------------------------------------


def projection(text):
    m = re.search(
        r'"proj":\{"kx":([\d.]+),"k":([\d.]+),"lat0":([\d.]+),"lon0":(-?[\d.]+)\}',
        text,
    )
    if not m:
        sys.exit("could not read the projection from geo.js")
    kx, k, lat0, lon0 = (float(g) for g in m.groups())
    return lambda lon, lat: ((lon - lon0) * kx, (lat0 - lat) * k)


def state_box(text):
    m = re.search(
        r'"bounds":\{"state":\[\[(-?[\d.]+),(-?[\d.]+)\],\[(-?[\d.]+),(-?[\d.]+)\]\]',
        text,
    )
    if not m:
        sys.exit("could not read the state box from geo.js")
    x0, y0, x1, y1 = (float(g) for g in m.groups())
    return [[x0, y0], [x1, y1]]


def typical_areas(text):
    """TypicalData.areas as typical.js writes it: id -> {title, wac}."""
    m = re.search(r'"areas":(\{.*?\}),"basemap"', text)
    if not m:
        sys.exit("could not read the areas from typical.js")
    return json.loads(m.group(1))


def rings_of(geometry):
    polys = (
        [geometry["coordinates"]]
        if geometry["type"] == "Polygon"
        else geometry["coordinates"]
    )
    rings = []
    for poly in polys:
        for ring in poly:
            pts = [(c[0], c[1]) for c in ring if len(c) >= 2]
            if len(pts) >= 2 and pts[0] == pts[-1]:
                pts = pts[:-1]
            if len(pts) >= 3:
                rings.append(pts)
    return rings


def load_source(path, errors):
    """id -> (title, [ring of (lon, lat)]) for every Washington feature."""
    try:
        gj = json.loads(Path(path).read_text())
        feats = gj["features"]
    except (OSError, ValueError, KeyError, TypeError) as e:
        errors.append(f"{path}: cannot read the marine areas ({e})")
        return {}
    out = {}
    for i, f in enumerate(feats):
        try:
            p, g = f["properties"], f["geometry"]
            name, title = p["AreaName"], p["AreaTitle"]
            if name == OREGON:  # MapScope.filter: Oregon regulates it
                continue
            rings = rings_of(g)
        except (KeyError, TypeError) as e:
            errors.append(f"feature {i}: malformed ({e})")
            continue
        if name in out:
            errors.append(f"area {name} appears twice in the source")
            continue
        out[name] = (title, rings)
    return out


# ---- geometry --------------------------------------------------------------


def extent(pts):
    xs = [p[0] for p in pts]
    ys = [p[1] for p in pts]
    return min(xs), min(ys), max(xs), max(ys)


def seg_dist(p, a, b):
    dx, dy = b[0] - a[0], b[1] - a[1]
    sq = dx * dx + dy * dy
    if sq == 0:
        return math.hypot(p[0] - a[0], p[1] - a[1])
    t = max(0.0, min(1.0, ((p[0] - a[0]) * dx + (p[1] - a[1]) * dy) / sq))
    return math.hypot(p[0] - (a[0] + t * dx), p[1] - (a[1] + t * dy))


def simplify_ring(pts, tol):
    """Douglas-Peucker on a closed ring: split it at the point farthest from the first
    one, so each half is an open chain, and keep a vertex that sits more than tol from
    the chord. Fewer than three vertices left means the ring collapsed: it is returned
    unchanged so the caller can decide."""
    n = len(pts)
    if n <= 3:
        return pts
    far = max(
        range(n),
        key=lambda i: (pts[i][0] - pts[0][0]) ** 2 + (pts[i][1] - pts[0][1]) ** 2,
    )
    ext = pts + [pts[0]]
    keep = [False] * (n + 1)
    keep[0] = keep[far] = keep[n] = True
    stack = [(0, far), (far, n)]
    while stack:
        i, j = stack.pop()
        if j <= i + 1:
            continue
        best, at = -1.0, -1
        for m in range(i + 1, j):
            d = seg_dist(ext[m], ext[i], ext[j])
            if d > best:
                best, at = d, m
        if best > tol:
            keep[at] = True
            stack.append((i, at))
            stack.append((at, j))
    out = [pts[i] for i in range(n) if keep[i]]
    return out if len(out) >= 3 else pts


def clip_ring(pts, box):
    """Sutherland-Hodgman against the window; used for bbox and centroid only."""
    (x0, y0), (x1, y1) = box
    edges = [
        (
            lambda p: p[0] >= x0,
            lambda a, b: (x0, a[1] + (b[1] - a[1]) * (x0 - a[0]) / (b[0] - a[0])),
        ),
        (
            lambda p: p[0] <= x1,
            lambda a, b: (x1, a[1] + (b[1] - a[1]) * (x1 - a[0]) / (b[0] - a[0])),
        ),
        (
            lambda p: p[1] >= y0,
            lambda a, b: (a[0] + (b[0] - a[0]) * (y0 - a[1]) / (b[1] - a[1]), y0),
        ),
        (
            lambda p: p[1] <= y1,
            lambda a, b: (a[0] + (b[0] - a[0]) * (y1 - a[1]) / (b[1] - a[1]), y1),
        ),
    ]
    out = pts
    for inside, cut in edges:
        if not out:
            break
        src, out = out, []
        prev = src[-1]
        for cur in src:
            if inside(cur):
                if not inside(prev):
                    out.append(cut(prev, cur))
                out.append(cur)
            elif inside(prev):
                out.append(cut(prev, cur))
            prev = cur
    return out


def ring_area(pts):
    s = 0.0
    for i in range(len(pts)):
        a, b = pts[i - 1], pts[i]
        s += a[0] * b[1] - b[0] * a[1]
    return s / 2


def centroid(pts):
    a = ring_area(pts)
    if abs(a) < 1e-9:
        return sum(p[0] for p in pts) / len(pts), sum(p[1] for p in pts) / len(pts)
    cx = cy = 0.0
    for i in range(len(pts)):
        p, q = pts[i - 1], pts[i]
        f = p[0] * q[1] - q[0] * p[1]
        cx += (p[0] + q[0]) * f
        cy += (p[1] + q[1]) * f
    return cx / (6 * a), cy / (6 * a)


def num(v):
    s = f"{v:.{DECIMALS}f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def path_of(rings):
    return "".join(
        "M" + " ".join(f"{num(x)} {num(y)}" for x, y in r) + "Z" for r in rings
    )


def build_area(title, rings, proj, window):
    """-> (entry, report) or (None, why)."""
    kept = []
    for ring in rings:
        pts = [proj(lon, lat) for lon, lat in ring]
        x0, y0, x1, y1 = extent(pts)
        if max(x1 - x0, y1 - y0) < MIN_RING:
            continue
        kept.append(simplify_ring(pts, TOLERANCE))
    if not kept:
        return None, "no ring left after dropping slivers"
    # Measured on what the camera can show.
    clipped = [c for c in (clip_ring(r, window) for r in kept) if len(c) >= 3]
    if not clipped:
        return None, "the outline is wholly outside the pan window"
    xs = [p[0] for r in clipped for p in r]
    ys = [p[1] for r in clipped for p in r]
    big = max(clipped, key=lambda r: abs(ring_area(r)))
    cx, cy = centroid(big)
    entry = {
        "title": title,
        "d": path_of(kept),
        "bbox": [
            [float(num(min(xs))), float(num(min(ys)))],
            [float(num(max(xs))), float(num(max(ys)))],
        ],
        "centroid": [float(num(cx)), float(num(cy))],
    }
    return entry, {
        "rings": len(kept),
        "dropped": len(rings) - len(kept),
        "points": sum(len(r) for r in kept),
    }


# ---- build and check --------------------------------------------------------


def build(src, errors):
    geo = GEO.read_text()
    proj = projection(geo)
    sb = state_box(geo)
    window = [
        [sb[0][0] - WINDOW_MARGIN, sb[0][1] - WINDOW_MARGIN],
        [sb[1][0] + WINDOW_MARGIN, sb[1][1] + WINDOW_MARGIN],
    ]
    want = typical_areas(TYPICAL.read_text())
    have = load_source(src, errors)
    if errors:
        return None, []
    for aid in want:
        if aid not in have:
            errors.append(f"typical.js has area {aid} but the source does not")
    for aid in have:
        if aid not in want:
            errors.append(f"the source has area {aid} that typical.js does not")
    entries, report = {}, []
    for aid in want:
        if aid not in have:
            continue
        title, rings = have[aid]
        if title != want[aid]["title"]:
            errors.append(
                f"area {aid}: source title {title!r} differs from typical.js {want[aid]['title']!r}"
            )
        entry, rep = build_area(title, rings, proj, window)
        if entry is None:
            errors.append(f"area {aid}: {rep}")
            continue
        entries[aid] = entry
        report.append((aid, rep))
    return entries, report


def render(entries):
    body = ",\n".join(
        "    " + json.dumps(aid) + ": " + json.dumps(e, ensure_ascii=False)
        for aid, e in entries.items()
    )
    return HEADER + TEMPLATE.replace("__BODY__", body)


def parse_file(text):
    m = re.search(r"return \{\n(.*)\n  \};\n\}\);", text, re.DOTALL)
    if not m or not text.startswith("/* Generated by scripts/build_marine_areas.py"):
        return None
    return json.loads("{" + m.group(1) + "}")


def check_file(text, errors):
    data = parse_file(text)
    if data is None:
        errors.append("marine-areas.js does not have the generated shape")
        return
    if len(text.encode()) > MAX_BYTES:
        errors.append(
            f"marine-areas.js is {len(text.encode())} bytes, over {MAX_BYTES}"
        )
    want = set(typical_areas(TYPICAL.read_text()))
    if set(data) != want:
        errors.append(
            f"marine-areas.js ids differ from typical.js areas: {sorted(set(data) ^ want)}"
        )
    for aid, e in data.items():
        if set(e) != {"title", "d", "bbox", "centroid"} or not e["d"].startswith("M"):
            errors.append(f"area {aid}: wrong keys or path")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument(
        "--src",
        default=str(SRC),
        help="WDFW marine areas GeoJSON (default: the gitignored build cache)",
    )
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    errors = []
    have_src = Path(args.src).exists()
    if args.check and not have_src:
        print(
            f"note: {args.src} is not present; checking marine-areas.js alone, not whether it is stale",
            file=sys.stderr,
        )
        if not OUT.exists():
            print("error: marine-areas.js is missing", file=sys.stderr)
            sys.exit(1)
        check_file(OUT.read_text(), errors)
        for e in errors:
            print("error:", e, file=sys.stderr)
        if errors:
            sys.exit(1)
        print(
            "marine-areas.js is well formed (source not present: staleness not checked)"
        )
        return

    entries, report = build(args.src, errors)
    text = render(entries) if entries is not None and not errors else None
    if text is not None and len(text.encode()) > MAX_BYTES:
        errors.append(
            f"marine-areas.js would be {len(text.encode())} bytes, over {MAX_BYTES}: raise TOLERANCE"
        )
    if errors:
        for e in errors:
            print("error:", e, file=sys.stderr)
        sys.exit(1)

    for aid, r in report:
        print(
            f"{aid}: {r['rings']} rings ({r['dropped']} dropped), {r['points']} points"
        )
    size = len(text.encode())
    if args.check:
        have = OUT.read_text() if OUT.exists() else None
        if have != text:
            print(
                "error: marine-areas.js is stale: rerun scripts/build_marine_areas.py",
                file=sys.stderr,
            )
            sys.exit(1)
        print(
            f"marine-areas.js matches the source ({size} bytes, tolerance {TOLERANCE})"
        )
        return
    OUT.write_text(text)
    print(
        f"wrote {OUT.name} {size} bytes, tolerance {TOLERANCE} map units, ring floor {MIN_RING}"
    )


if __name__ == "__main__":
    main()
