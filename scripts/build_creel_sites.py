#!/usr/bin/env python3
"""Write Artifacts/salmon-rivers/creel.js: recent WDFW angler-survey (creel) counts per map site.

    build_creel_sites.py [--window 15|30|60] [--refresh]
    build_creel_sites.py --fixture FILE        (print the match+sum result for a small fixture)

Source: https://wdfw.wa.gov/fishing/reports/creel/puget, the Puget Sound
Sampling Unit table. The page is server-rendered HTML, one table per sample day
(caption "Oct 17, 2026"), one row per ramp/site and catch area, paged with
?page=N and filtered with ?sample_date=1|2|3 (last 15|30|60 days) and
?ramp=<name>. The page says the numbers are raw and change after QA/QC.

Counts only. Nothing here feeds a rating, a pin colour or a species chip.

Rules this script keeps:
 * A value the source leaves blank is null, never 0. A real "0" stays 0. A
   window total is null if any sampled day in it is null.
 * A row that cannot be parsed goes to the not-parsed list in the report; it is
   never dropped silently, and an unknown column header fails the whole table
   the same way.
 * A ramp becomes a map site by exact normalized name, else by a reviewed
   entry in scripts/creel_crosswalk.json with confidence "high" (at least two
   independent pieces of evidence). "medium" entries are candidates for the
   owner to approve and are never applied. If the source gave coordinates (this
   one does not), either kind of match must also be within 1 km. A name shared
   by several sites is ambiguous and stays unmatched unless a high entry
   resolves it. There is no fuzzy matching: a wrong site is worse than a
   missing one.
 * Several source ramps that match one site (and the same catch area) are summed
   only when they were sampled on exactly the same set of days; otherwise they
   stay separate rows.
 * "Chinook (per angler)" is a rate, not a count. It is not kept.

Other creel pages, checked 2026-10-18 and left out (see the review file):
 buoy10 and willapa-bay publish one table for the whole fishery, no site or
 ramp column; north-coast-surveys is a per-river dataset (data.wa.gov), whose
 water-body names are run through the same matcher and reported, not emitted.
"""

