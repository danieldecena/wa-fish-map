# ---------------------------------------------------------------- html tables


@dataclass
class Table:
    caption: str = ""
    headers: list[str] = field(default_factory=list)
    rows: list[list[str]] = field(default_factory=list)


class TableParser(HTMLParser):
    """Collects every <table>: caption, <th> texts and the <td> texts of each body row."""

    def __init__(self) -> None:
        super().__init__(convert_charrefs=True)
        self.tables: list[Table] = []
        self._table: Table | None = None
        self._row: list[str] | None = None
        self._cell: list[str] | None = None
        self._kind = ""

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        del attrs  # unused; the name has to match HTMLParser's signature
        if tag == "table":
            self._table = Table()
        elif self._table is None:
            return
        elif tag == "caption":
            self._cell, self._kind = [], "caption"
        elif tag == "tr":
            self._row = []
        elif tag in ("td", "th"):
            self._cell, self._kind = [], tag

    def handle_data(self, data: str) -> None:
        if self._cell is not None:
            self._cell.append(data)

    def handle_endtag(self, tag: str) -> None:
        table = self._table
        if table is None:
            return
        if tag in ("caption", "td", "th") and self._cell is not None:
            text = re.sub(r"\s+", " ", "".join(self._cell)).strip()
            self._cell = None
            if tag == "caption":
                table.caption = text
            elif tag == "th":
                table.headers.append(text)
            elif self._row is not None:
                self._row.append(text)
        elif tag == "tr" and self._row is not None:
            if self._row:
                table.rows.append(self._row)
            self._row = None
        elif tag == "table":
            self.tables.append(table)
            self._table = None


def tables_of(page: str) -> list[Table]:
    p = TableParser()
    p.feed(page)
    p.close()
    return p.tables


# ---------------------------------------------------------------------- fetch


def fetch(url: str, name: str, refresh: bool) -> str:
    """The body of url, cached under .cache/wdfw/creel/<name>. A failed fetch raises."""
    path = CACHE / name
    if path.exists() and not refresh:
        return path.read_text()
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=60) as r:
        body = r.read().decode("utf-8")
    CACHE.mkdir(parents=True, exist_ok=True)
    path.write_text(body)
    return body


def cache_date(name: str) -> datetime.date:
    return (
        datetime.datetime.fromtimestamp((CACHE / name).stat().st_mtime)
        .astimezone()
        .date()
    )


# ---------------------------------------------------------------- source rows


@dataclass
class SourceRow:
    site: str
    catch_area: str
    date: str  # ISO, from the table caption
    interviews: int | None
    anglers: int | None
    species: dict[str, int | None]
    lat: float | None = None
    lon: float | None = None


@dataclass
class NotParsed:
    where: str
    reason: str
    cells: list[str]


def to_count(cell: str) -> tuple[bool, int | None]:
    """(ok, value). A blank cell is ok and None; a whole number is ok; anything else is not ok."""
    if cell == "":
        return True, None
    if re.fullmatch(r"\d+", cell):
        return True, int(cell)
    return False, None


def caption_date(caption: str) -> str | None:
    try:
        return (
            datetime.datetime.strptime(caption, "%b %d, %Y")
            .astimezone()
            .date()
            .isoformat()
        )
    except ValueError:
        return None


def parse_puget_tables(
    tables: list[Table], where: str
) -> tuple[list[SourceRow], list[NotParsed]]:
    rows: list[SourceRow] = []
    bad: list[NotParsed] = []
    for ti, t in enumerate(tables):
        label = f"{where} table {ti + 1} ({t.caption or 'no caption'})"
        known = (
            set(TEXT_COLUMNS)
            | set(COUNT_COLUMNS)
            | IGNORED_COLUMNS
            | set(SPECIES_COLUMNS)
        )
        unknown = [h for h in t.headers if h not in known]
        date = caption_date(t.caption)
        problem = ""
        if unknown:
            problem = f"unknown column header {unknown}"
        elif not {"Ramp/site", "Catch area", "Anglers"} <= set(t.headers):
            problem = "a required column is missing"
        elif date is None:
            problem = "caption is not a date"
        if problem:
            bad.extend(NotParsed(label, problem, r) for r in t.rows)
            continue
        assert date is not None
        for cells in t.rows:
            if len(cells) != len(t.headers):
                bad.append(
                    NotParsed(
                        label, f"{len(cells)} cells for {len(t.headers)} headers", cells
                    )
                )
                continue
            by = dict(zip(t.headers, cells))
            if by["Ramp/site"] == "":
                bad.append(NotParsed(label, "no ramp/site name", cells))
                continue
            values: dict[str, int | None] = {}
            failed = ""
            for h in list(COUNT_COLUMNS) + SPECIES_COLUMNS:
                if h not in by:
                    continue
                ok, v = to_count(by[h])
                if not ok:
                    failed = f"{h} = {by[h]!r} is not a whole number"
                    break
                values[h] = v
            if failed:
                bad.append(NotParsed(label, failed, cells))
                continue
            rows.append(
                SourceRow(
                    site=by["Ramp/site"],
                    catch_area=by["Catch area"],
                    date=date,
                    interviews=values.get("# Interviews (Boat or Shore)"),
                    anglers=values.get("Anglers"),
                    species={h: values[h] for h in SPECIES_COLUMNS if h in values},
                )
            )
    return rows, bad


def row_key(r: SourceRow) -> tuple[object, ...]:
    return (
        r.site,
        r.catch_area,
        r.date,
        r.interviews,
        r.anglers,
        tuple(r.species.items()),
    )


def drop_page_overlap(pages: list[list[SourceRow]]) -> tuple[list[SourceRow], int]:
    """All rows in page order, minus any row identical to one on an EARLIER page.

    The listing is paged and WDFW adds rows while it is read, so a row can show up
    again at the top of the next page. That is the same observation twice, and summing
    it would double that day's counts. Identical rows on one page are kept: the source
    can legitimately list two interviews with the same figures."""
    seen: set[tuple[object, ...]] = set()
    out: list[SourceRow] = []
    dropped = 0
    for rows in pages:
        for r in rows:
            if row_key(r) in seen:
                dropped += 1
            else:
                out.append(r)
        seen |= {row_key(r) for r in rows}
    return out, dropped


def fetch_window(
    days: int, refresh: bool
) -> tuple[list[SourceRow], list[NotParsed], list[str]]:
    """Every row of the Puget page for the last `days` days, all pages. Also the cache names used."""
    code = WINDOWS[days]
    pages: list[list[SourceRow]] = []
    bad: list[NotParsed] = []
    names: list[str] = []
    for n in range(MAX_PAGES):
        name = f"puget-sd{code}-p{n}.html"
        page = fetch(f"{PUGET}?sample_date={code}&page={n}", name, refresh)
        tables = tables_of(page)
        if not any(t.rows for t in tables):
            if n == 0:
                raise SystemExit(f"{PUGET} sample_date={code}: page 0 has no data rows")
            break
        names.append(name)
        got, nb = parse_puget_tables(tables, f"page {n}")
        pages.append(got)
        bad += nb
    else:
        raise SystemExit(f"more than {MAX_PAGES} pages; stopping rather than guessing")
    rows, dropped = drop_page_overlap(pages)
    if dropped:
        print(
            f"warning: dropped {dropped} rows that repeat a row from an earlier page",
            file=sys.stderr,
        )
    return rows, bad, names


def annual_year(page: str) -> int:
    """The season the annual page's first filter option stands for (the newest year)."""
    m = re.search(r'<select[^>]*name="sample_date".*?</select>', page, re.DOTALL)
    opt = re.search(r'<option value="1"[^>]*>\s*(\d{4})\s*<', m.group(0)) if m else None
    if opt is None:
        raise SystemExit("the annual page has no season filter; the page changed")
    return int(opt.group(1))


def fetch_annual(
    year: int, refresh: bool
) -> tuple[dict[str, tuple[str, int]], list[NotParsed]]:
    """Every ramp with a row this season on the annual page: (newest sampled day, number of sampled days)."""
    days: dict[str, set[str]] = defaultdict(set)
    bad: list[NotParsed] = []
    for n in range(MAX_PAGES):
        page = fetch(
            f"{PUGET_ANNUAL}?sample_date=1&page={n}",
            f"puget-annual-{year}-p{n}.html",
            refresh,
        )
        if n == 0 and annual_year(page) != year:
            raise SystemExit(
                f"the annual page's newest season is {annual_year(page)}, not {year}; stopping rather than guessing"
            )
        tables = tables_of(page)
        if not any(t.rows for t in tables):
            if n == 0:
                raise SystemExit(f"{PUGET_ANNUAL}: page 0 has no data rows")
            break
        got, nb = parse_puget_tables(tables, f"annual page {n}")
        bad += nb
        for r in got:
            days[r.site].add(r.date)
    else:
        raise SystemExit(f"more than {MAX_PAGES} pages; stopping rather than guessing")
    return {k: (max(v), len(v)) for k, v in days.items()}, bad


# ------------------------------------------------------------------- matching


def normalize(name: str) -> str:
    """Lower case, '&' as 'and', punctuation to spaces, spaces collapsed. Nothing else."""
    s = name.casefold().replace("&", " and ")
    return re.sub(r"\s+", " ", re.sub(r"[^a-z0-9]+", " ", s)).strip()


def metres(a: tuple[float, float], b: tuple[float, float]) -> float:
    (la1, lo1), (la2, lo2) = a, b
    p1, p2 = math.radians(la1), math.radians(la2)
    dp, dl = p2 - p1, math.radians(lo2 - lo1)
    h = math.sin(dp / 2) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(dl / 2) ** 2
    return 2 * 6371008.8 * math.asin(math.sqrt(h))


@dataclass
class Match:
    site_id: str | None
    rule: str  # 'exact-name' | 'name+coordinates' | 'crosswalk' | 'unmatched'
    why: str


@dataclass
class CrosswalkEntry:
    ramp: str
    site_id: str
    confidence: str
    evidence: list[str]
    note: str


@dataclass
class Crosswalk:
    """Reviewed ramp -> site entries, keyed by normalized ramp name. Only `high` is ever applied."""

    high: dict[str, CrosswalkEntry] = field(default_factory=dict)
    medium: dict[str, CrosswalkEntry] = field(default_factory=dict)
    no_match: dict[str, str] = field(default_factory=dict)  # normalized name -> reason
    names: dict[str, str] = field(
        default_factory=dict
    )  # normalized name -> name as written


def parse_crosswalk(data: object, site_ids: set[str]) -> Crosswalk:
    """Validate the crosswalk data. Anything malformed stops the build: a bad entry must not be skipped silently."""
    if not isinstance(data, dict):
        raise SystemExit(
            "creel_crosswalk.json: expected an object with an 'entries' list"
        )
    cw = Crosswalk()
    for i, e in enumerate(data.get("entries", [])):
        where = f"creel_crosswalk.json entry {i + 1}"
        if not isinstance(e, dict):
            raise SystemExit(f"{where}: not an object")
        ramp = e.get("wdfw_ramp_name")
        site_id = e.get("site_id")
        conf = e.get("confidence")
        evidence = e.get("evidence")
        note = e.get("note", "")
        if not isinstance(ramp, str) or not normalize(ramp):
            raise SystemExit(f"{where}: wdfw_ramp_name is missing")
        where = f"{where} ({ramp})"
        if not isinstance(site_id, str) or site_id not in site_ids:
            raise SystemExit(
                f"{where}: site_id {site_id!r} is not a site in sites.json"
            )
        if conf not in ("high", "medium"):
            raise SystemExit(
                f"{where}: confidence must be 'high' or 'medium', got {conf!r}"
            )
        if (
            not isinstance(evidence, list)
            or not evidence
            or not all(isinstance(x, str) and x.strip() for x in evidence)
        ):
            raise SystemExit(f"{where}: evidence must be a non-empty list of strings")
        if conf == "high" and len(evidence) < 2:
            raise SystemExit(
                f"{where}: a high entry needs at least two pieces of evidence"
            )
        key = normalize(ramp)
        if key in cw.names:
            raise SystemExit(f"{where}: ramp listed twice")
        cw.names[key] = ramp
        (cw.high if conf == "high" else cw.medium)[key] = CrosswalkEntry(
            ramp, site_id, conf, [str(x) for x in evidence], str(note)
        )
    for i, e in enumerate(data.get("reviewed_no_match", [])):
        ramp, reason = e.get("wdfw_ramp_name"), e.get("reason")
        if (
            not isinstance(ramp, str)
            or not isinstance(reason, str)
            or not reason.strip()
        ):
            raise SystemExit(
                f"creel_crosswalk.json reviewed_no_match {i + 1}: needs a ramp name and a reason"
            )
        key = normalize(ramp)
        if key in cw.names:
            raise SystemExit(
                f"{ramp}: listed in both entries and reviewed_no_match, or twice"
            )
        cw.names[key] = ramp
        cw.no_match[key] = reason
    return cw


def load_crosswalk(site_list: list[dict[str, object]]) -> Crosswalk:
    return parse_crosswalk(
        json.loads(CROSSWALK.read_text()), {str(s["id"]) for s in site_list}
    )


def match_name(
    name: str,
    by_name: dict[str, list[dict[str, object]]],
    lat: float | None = None,
    lon: float | None = None,
) -> Match:
    found = by_name.get(normalize(name), [])
    if not found:
        return Match(None, "unmatched", "no site has this normalized name")
    if lat is not None and lon is not None:
        near = [
            s
            for s in found
            if metres((lat, lon), (float(str(s["lat"])), float(str(s["lon"]))))
            <= MAX_METRES
        ]
        if len(near) == 1:
            return Match(
                str(near[0]["id"]),
                "name+coordinates",
                "same name and within 1 km of the source coordinates",
            )
        if not near:
            return Match(
                None,
                "unmatched",
                "the name matches but no such site is within 1 km of the source coordinates",
            )
        return Match(
            None, "unmatched", f"{len(near)} sites with this name are within 1 km"
        )
    if len(found) == 1:
        return Match(
            str(found[0]["id"]),
            "exact-name",
            "same normalized name; the source gives no coordinates",
        )
    return Match(
        None,
        "unmatched",
        f"ambiguous: {len(found)} sites share this name and the source gives no coordinates",
    )


def match_ramp(
    name: str,
    by_name: dict[str, list[dict[str, object]]],
    crosswalk: Crosswalk,
    by_id: dict[str, dict[str, object]],
    lat: float | None = None,
    lon: float | None = None,
) -> Match:
    """Exact normalized name first; only if that finds nothing, a high crosswalk entry."""
    m = match_name(name, by_name, lat, lon)
    if m.site_id is not None:
        return m
    entry = crosswalk.high.get(normalize(name))
    if entry is None:
        return m
    site = by_id[entry.site_id]
    far = (
        lat is not None
        and lon is not None
        and metres((lat, lon), (float(str(site["lat"])), float(str(site["lon"]))))
        > MAX_METRES
    )
    if far:
        return Match(
            None,
            "unmatched",
            "a high crosswalk entry names this ramp but the site is more than 1 km from the source coordinates",
        )
    return Match(
        entry.site_id,
        "crosswalk",
        "reviewed crosswalk entry, high confidence (see scripts/creel_crosswalk.json)",
    )


def total(values: list[int | None]) -> int | None:
    """Sum, or None if there is nothing or any day did not state it."""
    if not values or any(v is None for v in values):
        return None
    return sum(v for v in values if v is not None)


@dataclass
class Group:
    """One source ramp in one catch area: its sample days and window totals."""

    ramp: str
    catch_area: str
    days: dict[str, SourceRow]
    rule: str = ""

    @property
    def dates(self) -> list[str]:
        return sorted(self.days)


def group_rows(rows: list[SourceRow]) -> list[Group]:
    """One Group per (ramp, catch area). Two rows for the same ramp, area and day are summed into that day."""
    out: dict[tuple[str, str], Group] = {}
    for r in rows:
        g = out.setdefault((r.site, r.catch_area), Group(r.site, r.catch_area, {}))
        if r.date in g.days:
            old = g.days[r.date]
            merged = {
                k: total([old.species.get(k), r.species.get(k)])
                for k in SPECIES_COLUMNS
                if k in r.species
            }
            g.days[r.date] = SourceRow(
                r.site,
                r.catch_area,
                r.date,
                total([old.interviews, r.interviews]),
                total([old.anglers, r.anglers]),
                merged,
            )
        else:
            g.days[r.date] = r
    return list(out.values())


def window_row(groups: list[Group], source: str) -> dict[str, object]:
    """Sum the given groups (already known to share one sample-day set) into one creel.js row."""
    dates = groups[0].dates
    days = [g.days[d] for g in groups for d in dates]
    species = {
        k: total([d.species.get(k) for d in days])
        for k in SPECIES_COLUMNS
        if k in days[0].species
    }
    return {
        "ramp": " + ".join(sorted(g.ramp for g in groups)),
        "catchArea": groups[0].catch_area,
        "windowStart": dates[0],
        "windowEnd": dates[-1],
        "surveyDays": len(dates),
        "match": " + ".join(sorted({g.rule for g in groups})),
        "interviews": total([d.interviews for d in days]),
        "anglers": total([d.anglers for d in days]),
        "species": species,
        "source": source,
    }


@dataclass
class Assembled:
    sites: dict[str, dict[str, object]]
    matched: list[tuple[str, Match, list[Group]]]  # source ramp, match, its groups
    unmatched: list[tuple[str, Match, list[Group]]]
    summed: list[str]  # human notes on many-to-one sums and refusals


def assemble(
    site_list: list[dict[str, object]],
    rows: list[SourceRow],
    filter_label: str,
    source_for: dict[str, str],
    crosswalk: Crosswalk | None = None,
) -> Assembled:
    crosswalk = crosswalk or Crosswalk()
    by_name = _index(site_list)
    by_id = {str(s["id"]): s for s in site_list}
    ramps: dict[str, list[SourceRow]] = defaultdict(list)
    for r in rows:
        ramps[r.site].append(r)
    coords = {
        r.site: (r.lat, r.lon) for r in rows if r.lat is not None and r.lon is not None
    }
    matched: list[tuple[str, Match, list[Group]]] = []
    unmatched: list[tuple[str, Match, list[Group]]] = []
    per_site: dict[str, list[Group]] = defaultdict(list)
    for ramp in sorted(ramps):
        lat, lon = coords.get(ramp, (None, None))
        m = match_ramp(ramp, by_name, crosswalk, by_id, lat, lon)
        groups = group_rows(ramps[ramp])
        if m.site_id is None:
            unmatched.append((ramp, m, groups))
            continue
        for g in groups:
            g.rule = m.rule
        matched.append((ramp, m, groups))
        per_site[m.site_id] += groups
    sites: dict[str, dict[str, object]] = {}
    notes: list[str] = []
    for sid, groups in sorted(per_site.items()):
        by_area: dict[str, list[Group]] = defaultdict(list)
        for g in groups:
            by_area[g.catch_area].append(g)
        out_rows: list[dict[str, object]] = []
        for area, gs in sorted(by_area.items()):
            same: dict[tuple[str, ...], list[Group]] = defaultdict(list)
            for g in gs:
                same[tuple(g.dates)].append(g)
            if len(gs) > 1:
                kind = (
                    "summed"
                    if len(same) == 1
                    else f"kept separate ({len(same)} different sample-day sets)"
                )
                notes.append(
                    f"{sid} / {area}: {len(gs)} source ramps ({', '.join(sorted(g.ramp for g in gs))}) {kind}"
                )
            for _, same_gs in sorted(same.items()):
                out_rows.append(window_row(same_gs, source_for[same_gs[0].ramp]))
        sites[sid] = {
            "filter": filter_label,
            "windowStart": min(str(r["windowStart"]) for r in out_rows),
            "windowEnd": max(str(r["windowEnd"]) for r in out_rows),
            "rows": out_rows,
        }
    return Assembled(sites, matched, unmatched, notes)


