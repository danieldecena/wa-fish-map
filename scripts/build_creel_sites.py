def from_fixture(path: Path) -> dict[str, object]:
    fx = json.loads(path.read_text())
    rows = [
        SourceRow(
            site=r["site"],
            catch_area=r.get("catch_area", "Area X"),
            date=r["date"],
            interviews=r.get("interviews"),
            anglers=r.get("anglers"),
            species=r.get("species", {}),
            lat=r.get("lat"),
            lon=r.get("lon"),
        )
        for r in fx["rows"]
    ]
    src = {
        r.site: "https://example.invalid/" + urllib.parse.quote(r.site) for r in rows
    }
    crosswalk = parse_crosswalk(
        {"entries": fx.get("crosswalk", [])}, {str(s["id"]) for s in fx["sites"]}
    )
    a = assemble(fx["sites"], rows, "fixture", src, crosswalk)
    return {
        "sites": a.sites,
        "matched": {ramp: [m.site_id, m.rule] for ramp, m, _ in a.matched},
        "unmatched": {ramp: m.why for ramp, m, _ in a.unmatched},
        "notes": a.summed,
    }


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument(
        "--window", type=int, choices=sorted(WINDOWS), default=DEFAULT_WINDOW
    )
    ap.add_argument(
        "--refresh",
        action="store_true",
        help="fetch every page again instead of using .cache/wdfw/creel",
    )
    ap.add_argument(
        "--fixture",
        type=Path,
        help="print the match and sum result for a fixture file, write nothing",
    )
    args = ap.parse_args()
    if args.fixture:
        print(json.dumps(from_fixture(args.fixture), indent=2, sort_keys=True))
        return

    today = datetime.datetime.now().astimezone().date()
    site_list = load_sites()
    crosswalk = load_crosswalk(site_list)
    rows, unparsed, names = fetch_window(args.window, args.refresh)
    if not rows:
        raise SystemExit("no rows parsed")
    dup = len(rows) - len(
        {
            (
                r.site,
                r.catch_area,
                r.date,
                r.interviews,
                r.anglers,
                tuple(r.species.items()),
            )
            for r in rows
        }
    )
    if dup:
        print(
            f"warning: {dup} rows repeat another row on the same page; kept, since the source can list identical interviews",
            file=sys.stderr,
        )

    label = f"Last {args.window} days"
    code = WINDOWS[args.window]
    src: dict[str, str] = {
        r.site: f"{PUGET}?"
        + urllib.parse.urlencode({"ramp": r.site, "sample_date": code})
        for r in rows
    }
    a = assemble(site_list, rows, label, src, crosswalk)

    # Cross-check each matched ramp against the page's own ramp-filtered view.
    for ramp, _, groups in a.matched:
        page = fetch(
            src[ramp],
            f"puget-sd{code}-ramp-{re.sub(r'[^a-z0-9]+', '-', ramp.casefold())}.html",
            args.refresh,
        )
        own, own_bad = [], []
        for n in range(MAX_PAGES):
            pg = (
                page
                if n == 0
                else fetch(
                    src[ramp] + f"&page={n}",
                    f"puget-sd{code}-ramp-{re.sub(r'[^a-z0-9]+', '-', ramp.casefold())}-p{n}.html",
                    args.refresh,
                )
            )
            ts = tables_of(pg)
            if not any(t.rows for t in ts):
                break
            got, nb = parse_puget_tables(ts, f"ramp page {n}")
            own += got
            own_bad += nb
        mine = {
            (g.catch_area, d): (
                g.days[d].interviews,
                g.days[d].anglers,
                tuple(g.days[d].species.items()),
            )
            for g in group_rows(own)
            for d in g.dates
        }
        full = {
            (g.catch_area, d): (
                g.days[d].interviews,
                g.days[d].anglers,
                tuple(g.days[d].species.items()),
            )
            for g in groups
            for d in g.dates
        }
        if mine != full or own_bad:
            raise SystemExit(
                f"{ramp}: the ramp-filtered page disagrees with the full listing ({len(mine)} vs {len(full)} ramp-days, {len(own_bad)} not parsed)"
            )

    # The counts are as of the day the pages were fetched, not the day this script ran: a cached page
    # is reused until --refresh, and the file must not claim a newer date than its data has.
    fetched = min(cache_date(n) for n in names)
    generated = fetched.isoformat()
    if fetched != today:
        print(
            f"warning: the pages were fetched {fetched}, {(today - fetched).days} day(s) ago, so creel.js is dated {fetched}. Run with --refresh for today's counts.",
            file=sys.stderr,
        )
    js = render_js(a.sites, generated)
    if len(js.encode()) > SIZE_CAP:
        raise SystemExit(
            f"creel.js would be {len(js.encode())} bytes, over the {SIZE_CAP} cap; nothing written"
        )

    # Review file: dropdown, whole-season ramp table, other sources.
    dd = dropdown_ramps(fetch(PUGET, "puget-form.html", args.refresh))
    dd_keys = {normalize(n) for n in dd}
    missing = sorted(n for k, n in crosswalk.names.items() if k not in dd_keys)
    if missing:
        raise SystemExit(
            f"creel_crosswalk.json names ramps that are not in the Puget page's ramp dropdown (misspelled or renamed): {missing}"
        )
    season = today.year
    seen, annual_bad = fetch_annual(season, args.refresh)
    unparsed = unparsed + annual_bad
    recent_days = {
        site: len({r.date for r in rows if r.site == site})
        for site in {r.site for r in rows}
    }
    # A ramp sampled late last year is missing from this year's annual page.
    for site, n_days in recent_days.items():
        if site not in seen:
            seen[site] = (max(r.date for r in rows if r.site == site), n_days)
    north = north_coast_waters(60, today, args.refresh)
    by_name = _index(site_list)
    north_matches = [(w, match_name(w, by_name)) for w, _, _ in north]
    shapes = {
        "Buoy 10": table_shapes(BUOY10, "buoy10.html", args.refresh),
        "Willapa Bay": table_shapes(WILLAPA, "willapa-bay.html", args.refresh),
    }
    for label_, ts in shapes.items():
        if not ts:
            raise SystemExit(f"{label_}: no tables found; the page changed")
    review = render_review(
        a,
        site_list,
        args.window,
        generated,
        unparsed,
        dd,
        north,
        north_matches,
        shapes,
        crosswalk,
        season,
        seen,
        recent_days,
    )
    OUT.write_text(js)
    REVIEW.write_text(review)

    dates = sorted({r.date for r in rows})
    print(
        f"puget {label}: {len(rows)} rows, {len({r.site for r in rows})} ramps, sampled days {dates[0]} to {dates[-1]}, fetched {fetched}, {len(names)} pages"
    )
    print(f"not parsed: {len(unparsed)}")
    print(
        f"matched ramps: {len(a.matched)} ({sum(1 for _, m, _ in a.matched if m.rule == 'crosswalk')} by crosswalk); map sites with counts: {len(a.sites)}; unmatched ramps: {len(a.unmatched)}"
    )
    for ramp, _, _ in a.unmatched:
        print(f"  unmatched: {ramp}")
    print(
        f"north coast: {len(north)} water bodies, matched {sum(1 for _, m in north_matches if m.site_id)}"
    )
    print(f"creel.js {len(js.encode())} bytes")


if __name__ == "__main__":
    main()
