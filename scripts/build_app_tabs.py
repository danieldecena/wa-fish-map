        ('--r-prime: #f01c0d; --r-good: #ff7300; --r-fair: #ffc700; --r-slow: #0073ff; --r-none: #8e8e93;',
         '--r-prime: #FF3B30; --r-good: #FF9500; --r-fair: #FFCC00; --r-slow: #007AFF; --r-none: #8E8E93;', 1),
        ('--accent: #0068DA;', '--accent: #0058B9;', 1),
        ('--accent: #409CFF;', '--accent: #5DABFF;', 2),
        ('--bad: #FF6A63; --bad-wash: #51241F; color-scheme: dark;',
         '--bad: #FF6A63; --bad-wash: #51241F; color-scheme: dark;\n'
         '    --r-prime: #FF453A; --r-good: #FF9F0A; --r-fair: #FFD60A; --r-slow: #0A84FF; --r-none: #98989D;', 2),
        ('"SF Pro", "Helvetica Neue", system-ui, sans-serif;', '"SF Pro", system-ui, sans-serif;', 2),
