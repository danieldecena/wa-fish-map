    rest = rest.rstrip()
    assert rest.endswith('</body></html>')
    rest = rest[:-len('</body></html>')].rstrip('\n')
    cut = rest.index('</style>') + len('</style>')
    head_src, body_src = rest[:cut], rest[cut:].lstrip('\n')
    assert head_src.startswith('<title>Three Friends Fishing Hole</title>')
    # App Kit alignment. Rating colours become the Map's Apple system colours (light here, dark in
    # both dark blocks); the link colour becomes App Kit accent-ink; font stacks drop non-SF fallbacks;
    # panels take radius-lg and the badge App Kit's 3px 8px padding. (old, new, expected count)
