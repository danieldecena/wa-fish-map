def counts_page():
    # No skeleton in the source; head material ends at the page's </style>.
    src = (ART / 'salmon-catch-table' / 'index.html').read_text()
    cut = src.index('</style>') + len('</style>')
    head_src, body_src = src[:cut], src[cut:].lstrip('\n')
    assert head_src.startswith('<title>SW Washington Creel Table</title>') and 'fonts.googleapis.com' in head_src
    FONTS = ('<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=IBM+Plex+Mono:wght@400;600'
             '&family=IBM+Plex+Sans:wght@400;600&display=swap">\n')
    assert head_src.count(FONTS) == 1
    head_src = head_src.replace(FONTS, '')
    s0 = head_src.index('<style>')
    old_css = head_src[s0:]
    assert hashlib.sha256(old_css.encode()).hexdigest() == 'e4157e8f7c76695c8fa5317a85bd6fbcab25ba587560c13df57a604052beb135', \
        'salmon-catch-table CSS changed in the repo: port the change into COUNTS_CSS, then update this hash'
    head_src = head_src[:s0] + COUNTS_CSS
    # This page pads <body> (20px top, max(16px, safe-area) sides), so the bar would sit inset
    # inside that padding. Pull it out to the viewport edges and keep the original 20px above <main>.
    OFFSET = ('<style>/* tab bar offset for this page only: cancel body padding so the bar is full-bleed and flush to the top */\n'
              '.apptabs{margin:-20px calc(-1 * max(16px,env(safe-area-inset-right,0px))) 20px calc(-1 * max(16px,env(safe-area-inset-left,0px)))}</style>\n')
    return page(head_src, body_src, 'Counts', OFFSET)


def check_map():
    """The Map page carries the tab bar by hand; it must match what the sub-pages get."""
    html = (OUT / 'index.html').read_text()
    problems = []
    if CSS not in html:
        problems.append('salmon-rivers/index.html does not carry tabbar.css verbatim')
    if nav('Map', '') not in html:
        problems.append('salmon-rivers/index.html does not carry the Map tab bar nav verbatim: ' + nav('Map', '').strip())
    return problems


def outputs():
    return {
        OUT / 'year' / 'index.html': year_page().encode(),
        OUT / 'year' / 'data.js': (ART / 'fishing-year' / 'data.js').read_bytes(),
        OUT / 'spots' / 'index.html': spots_page().encode(),
        OUT / 'counts' / 'index.html': counts_page().encode(),
        OUT / 'counts' / 'data.js': (ART / 'salmon-catch-table' / 'data.js').read_bytes(),
    }


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--check', action='store_true', help='write nothing; exit 1 if a tab file is out of date')
    args = ap.parse_args()

    problems = check_map()
    files = outputs()
    if args.check:
        for path, data in files.items():
            if not path.exists() or path.read_bytes() != data:
                problems.append(f'{path.relative_to(ROOT)} is out of date: run scripts/build_app_tabs.py')
    else:
        for path, data in files.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
            print(f'wrote {path.relative_to(ROOT)} ({len(data):,} bytes)')
    for p in problems:
        print('error: ' + p, file=sys.stderr)
    return 1 if problems else 0


if __name__ == '__main__':
    sys.exit(main())
