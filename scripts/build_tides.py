#!/usr/bin/env python3
"""Write Artifacts/salmon-rivers/tides-data.js from NOAA CO-OPS predictions.

    build_tides.py [--days 45] [--start YYYY-MM-DD]
    build_tides.py --check            # validate the existing file, no network

Generated file: do not hand-edit. The published page runs in a frame that only
allows claude.ai connections, so the page makes no network requests; instead
this script fetches high/low predictions (MLLW, feet, station local time, the
same query the page used to make) for every station in STATIONS and bundles
them. Re-run at least monthly; the Week tab says through which date it has.

Fails loudly (non-zero) on an HTTP error, a NOAA `error` object, an empty
station or a time series that does not increase. The file is written to a temp
file and renamed, so a failed run never leaves a partial file.

Predictions, not observations. Heights are never a rating.
"""

