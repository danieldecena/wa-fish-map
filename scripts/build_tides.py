TIME_RE = re.compile(r"^\d{4}-\d{2}-\d{2} \d{2}:\d{2}$")


class BuildError(Exception):
    pass


def today_la():
    return datetime.datetime.now(ZoneInfo("America/Los_Angeles")).date()


def query_url(station_id, start, end):
    q = {
        "product": "predictions",
        "datum": "MLLW",
        "interval": "hilo",
        "units": "english",
        "time_zone": "lst_ldt",
        "format": "json",
        "station": station_id,
        "begin_date": start.strftime("%Y%m%d"),
        "end_date": end.strftime("%Y%m%d"),
    }
    return BASE + "?" + urllib.parse.urlencode(q)


def parse_predictions(payload, station_id):
    """NOAA JSON -> [[ "YYYY-MM-DD HH:MM", "H"|"L", feet ], ...], validated."""
    if not isinstance(payload, dict):
        raise BuildError(f"{station_id}: response is not a JSON object")
    if "error" in payload:
        err = payload["error"]
        msg = err.get("message") if isinstance(err, dict) else err
        raise BuildError(f"{station_id}: NOAA error: {msg}")
    rows = payload.get("predictions")
    if not isinstance(rows, list) or not rows:
        raise BuildError(f"{station_id}: no predictions")
    out = []
    for p in rows:
        t, typ = p.get("t"), p.get("type")
        if not isinstance(t, str) or not TIME_RE.match(t):
            raise BuildError(f"{station_id}: bad time {t!r}")
        if typ not in ("H", "L"):
            raise BuildError(f"{station_id}: bad type {typ!r} at {t}")
        try:
            v = round(float(p["v"]), 2)
        except (KeyError, TypeError, ValueError):
            raise BuildError(f"{station_id}: bad height at {t}")
        out.append([t, typ, v])
    check_monotonic(out, station_id)
    return out


def check_monotonic(rows, station_id):
    for a, b in zip(rows, rows[1:]):
        if b[0] <= a[0]:
            raise BuildError(f"{station_id}: times not increasing ({a[0]} then {b[0]})")


def fetch(station_id, start, end):
    url = query_url(station_id, start, end)
    try:
        with urllib.request.urlopen(url, timeout=60) as r:
            payload = json.load(r)
    except (urllib.error.URLError, OSError, ValueError) as e:
        raise BuildError(f"{station_id}: request failed: {e}")
    return parse_predictions(payload, station_id)


def build(start, days, fetcher=None):
    fetcher = fetcher or fetch
    end = start + datetime.timedelta(days=days - 1)
    preds = {}
    for sid, _name, _lat, _lon in STATIONS:
        rows = fetcher(sid, start, end)
        first, last = rows[0][0][:10], rows[-1][0][:10]
        if first > (start + datetime.timedelta(days=1)).isoformat() or last < (end - datetime.timedelta(days=1)).isoformat():
            raise BuildError(f"{sid}: predictions cover {first}..{last}, wanted {start}..{end}")
        preds[sid] = [r for r in rows if start.isoformat() <= r[0][:10] <= end.isoformat()]
        print(f"  {sid} {len(preds[sid])} extremes", file=sys.stderr)
    return {
        "generated": today_la().isoformat(),
        "start": start.isoformat(),
        "end": end.isoformat(),
        "stations": [{"id": i, "name": n, "lat": la, "lon": lo} for i, n, la, lo in STATIONS],
        "predictions": preds,
    }


def render(bundle):
    body = json.dumps(bundle, separators=(",", ":"))
    return HEADER.format(generated=bundle["generated"]) + "window.TIDES=" + body + ";\n"


def parse_file(text):
    m = re.search(r"window\.TIDES=(\{.*\});\s*$", text, re.S)
    if not m:
        raise BuildError("not a tides-data.js file")
    return json.loads(m.group(1))


def validate(bundle):
    """Raise BuildError unless the bundle is complete and consistent."""
    for k in ("generated", "start", "end", "stations", "predictions"):
        if k not in bundle:
            raise BuildError(f"missing {k}")
    d0 = datetime.date.fromisoformat(bundle["start"])
    d1 = datetime.date.fromisoformat(bundle["end"])
    if d1 < d0:
        raise BuildError("end before start")
    n = (d1 - d0).days + 1
    if not bundle["stations"]:
        raise BuildError("no stations")
    for s in bundle["stations"]:
        sid = s["id"]
        if not re.fullmatch(r"\d{7}", sid):
            raise BuildError(f"{sid}: id is not 7 digits")
        rows = bundle["predictions"].get(sid)
        if not rows:
            raise BuildError(f"{sid}: no predictions")
        check_monotonic(rows, sid)
        days = {r[0][:10] for r in rows}
        for i in range(n):
            d = (d0 + datetime.timedelta(days=i)).isoformat()
            if d not in days:
                raise BuildError(f"{sid}: no predictions on {d}")
        if rows[0][0][:10] < bundle["start"] or rows[-1][0][:10] > bundle["end"]:
            raise BuildError(f"{sid}: predictions outside {bundle['start']}..{bundle['end']}")
    return n


def write_atomic(path, text):
    path = Path(path)
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=path.name + ".", suffix=".tmp")
    try:
        with os.fdopen(fd, "w") as f:
            f.write(text)
        os.chmod(tmp, 0o644)
        os.replace(tmp, path)
    except BaseException:
        if os.path.exists(tmp):
            os.unlink(tmp)
        raise


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--days", type=int, default=45)
    ap.add_argument("--start", help="YYYY-MM-DD (default: today in America/Los_Angeles)")
    ap.add_argument("--check", action="store_true", help="validate the existing file; no network")
    ap.add_argument("--out", default=str(OUT))
    a = ap.parse_args(argv)
    try:
        if a.check:
            bundle = parse_file(Path(a.out).read_text())
            n = validate(bundle)
            print(f"ok: {len(bundle['stations'])} stations, {n} days, {bundle['start']}..{bundle['end']}")
            return 0
        if a.days < 1:
            raise BuildError("--days must be at least 1")
        start = datetime.date.fromisoformat(a.start) if a.start else today_la()
        bundle = build(start, a.days)
        validate(bundle)
        text = render(bundle)
        write_atomic(a.out, text)
        print(f"wrote {a.out}: {len(bundle['stations'])} stations, {a.days} days, {len(text) / 1024:.0f} KB")
        return 0
    except (BuildError, OSError, ValueError) as e:
        print(f"build_tides: {e}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
